"""Generate the GitLab pipeline configuration handed to GitLab by the datadog-agent-ci DDCI task engine."""

from __future__ import annotations

from typing import Any

from utils.gitlab.context import is_no_code_change

SOURCE_FILE = "gitlab-source.yml"
OUTPUT_FILE = "gitlab-config.yml"
NO_CODE_JOB = "no_code_change"
NO_CODE_MESSAGE = "No code modified, GG"
# Image variables copied from the source so the no-code job runs on the buildimage pinned in the repository
IMAGE_VARIABLES = ("CI_IMAGE_LINUX", "CI_IMAGE_LINUX_SUFFIX")

HEADER = f"# Generated by `dda gitlab generate` from {SOURCE_FILE}, do not edit.\n"


def generate(source: str, context: dict[str, Any] | None = None) -> str:
    """Return the pipeline configuration built from the content of the source configuration.

    Without a change context, the full pipeline is generated.
    """
    if context is not None and is_no_code_change(context):
        return HEADER + _dump(no_code_config(source))
    return HEADER + source


def no_code_config(source: str) -> dict[str, Any]:
    variables = _load(source).get("variables") or {}
    missing = [name for name in IMAGE_VARIABLES if name not in variables]
    if missing:
        raise ValueError(f"Variables {', '.join(missing)} not found in the source configuration")

    return {
        "variables": {name: variables[name] for name in IMAGE_VARIABLES},
        NO_CODE_JOB: {
            # A pipeline made only of .pre or .post jobs is not created, so use a regular default stage
            "stage": "test",
            "image": "registry.ddbuild.io/ci/datadog-agent-buildimages/linux$CI_IMAGE_LINUX_SUFFIX:$CI_IMAGE_LINUX",
            "tags": ["arch:amd64", "specific:true"],
            "needs": [],
            "variables": {"GIT_STRATEGY": "none"},
            "script": [f'echo "{NO_CODE_MESSAGE}"'],
        },
    }


def load_context(content: str) -> dict[str, Any]:
    import json

    try:
        context = json.loads(content)
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid change context: {e}") from e
    if not isinstance(context, dict):
        raise ValueError("Invalid change context: expected a JSON object")
    return context


def _load(source: str) -> dict[str, Any]:
    import yaml

    class _Loader(yaml.SafeLoader):
        pass

    # Only the variables are read, so GitLab tags such as !reference can be ignored
    _Loader.add_multi_constructor("!", lambda loader, suffix, node: None)
    return yaml.load(source, Loader=_Loader) or {}  # noqa: S506


def _dump(config: dict[str, Any]) -> str:
    import yaml

    return yaml.safe_dump(config, sort_keys=False, default_flow_style=False)


def main(argv: list[str] | None = None) -> int:
    """Entry point for callers without dda, such as the DDCI task engine, see .gitlab/generator.yml"""
    import argparse
    import sys

    parser = argparse.ArgumentParser(prog="python3 -m utils.gitlab.generate", description=__doc__)
    parser.add_argument("--context", help="Path to the change context JSON, `-` for stdin")
    parser.add_argument("--source", default=SOURCE_FILE, help="Path to the source GitLab configuration")
    parser.add_argument(
        "--output", "-o", default=OUTPUT_FILE, help="Path of the generated configuration, `-` for stdout"
    )
    args = parser.parse_args(argv)

    try:
        context = None
        if args.context == "-":
            context = load_context(sys.stdin.read())
        elif args.context:
            with open(args.context, encoding="utf-8") as f:
                context = load_context(f.read())
        with open(args.source, encoding="utf-8") as f:
            config = generate(f.read(), context)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    if args.output == "-":
        sys.stdout.write(config)
    else:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(config)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
