def _git_paths(*args):
    return [os.fsdecode(p) for p in subprocess.check_output(["git", *args]).split(b"\0") if p]


def _staged_paths(ctx):
    """Include both ends of renames so moving a settings file invalidates its old scope."""
    return _git_paths("diff", "--cached", "--no-renames", "--name-only", "-z", "--")


def _tracked_paths(ctx):
    paths = set()
    for entry in _git_paths("ls-files", "--stage", "-z"):
        metadata, path = entry.split("\t", 1)
        mode, _, stage = metadata.split()
        if stage != "0":
            raise Exit(f"Resolve the index conflict in {path} before validation.")
        if mode in {"100644", "100755"}:
            paths.add(path)
    return paths


def _staged_bytes(ctx, path):
    return subprocess.check_output(["git", "cat-file", "blob", ":" + path])


def _staged_blobs(paths):
    """Stream canonical file contents, including paths with newlines, through one Git process."""
    with subprocess.Popen(["git", "cat-file", "--batch", "-z"], stdin=subprocess.PIPE, stdout=subprocess.PIPE) as git:
        try:
            for path in paths:
                git.stdin.write(b":" + os.fsencode(path) + b"\0")
                git.stdin.flush()
                header = git.stdout.readline().split()
                if len(header) != 3 or header[1] != b"blob":
                    raise Exit(f"Cannot read staged file {path}.")
                size = int(header[2])
                contents = git.stdout.read(size)
                if len(contents) != size or git.stdout.read(1) != b"\n":
                    raise Exit(f"Incomplete Git blob for {path}.")
                yield path, contents
        finally:
            git.stdin.close()
        if git.wait():
            raise Exit("Cannot read the Git index.")


def _changed_paths(ctx, base):
    if base:
        return _git_paths("diff", "--no-renames", "--name-only", "-z", base, "HEAD", "--")
    return _staged_paths(ctx)


def _write_blob(directory, path, data):
    target = Path(directory, path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)


def _run_files(command, paths, directory, *, list_differences=False):
    # Keep explicit paths within Windows' command-line limit. Prefixing ./ also protects leading dashes.
    batch = []
    length = 0
    for path in paths:
        if batch and length + len(path) > 12000:
            _run_batch(command, batch, directory, list_differences)
            batch, length = [], 0
        batch.append("./" + path)
        length += len(path) + 5
    if batch:
        _run_batch(command, batch, directory, list_differences)


def _run_batch(command, batch, directory, list_differences):
    result = subprocess.run([*command, *batch], cwd=directory, stdout=subprocess.PIPE if list_differences else None)
    if result.stdout:
        print(os.fsdecode(result.stdout).rstrip(), file=sys.stderr)
    if result.returncode or result.stdout:
        raise Exit(f"{Path(command[0]).name} reported problems.", code=result.returncode or 1)


def _go_generated(data, mode):
    # golangci-lint checks comments preceding the package clause.
    header = re.split(rb"(?m)^\s*package\s", data, maxsplit=1)[0]
    if mode == "strict":
        return re.search(rb"(?m)^// Code generated .* DO NOT EDIT\.\r?$", header)
    if mode == "lax":
        return re.search(
            rb"code generated|do not edit|autogenerated file|\* generated by: swagger codegen ", header, re.I
        )
    if mode != "disable":
        raise Exit(f"Unknown golangci-lint generated-file mode {mode!r}.")
    return False


@task(help={"base": "In CI, select paths changed between this commit and HEAD."})
def check_go_fmt(ctx, all_files=False, base=""):
    """Check staged Go formatting and simplification against CI's formatter exclusions."""
    tracked = _tracked_paths(ctx)
    changed = set(_changed_paths(ctx, base))
    candidates = tracked if all_files or changed & {".go-version", ".golangci.yml"} else tracked & changed
    files = sorted(p for p in candidates if p.endswith(".go") and not p.endswith((".pb.go", "_gen.go")))
    if not files:
        return
    exclusions = {}
    if ".golangci.yml" in tracked:
        exclusions = (
            (yaml.safe_load(_staged_bytes(ctx, ".golangci.yml")) or {}).get("formatters", {}).get("exclusions", {})
        )
    patterns = [re.compile(p) for p in exclusions.get("paths", [])]
    with TemporaryDirectory() as directory:
        selected = []
        for path, data in _staged_blobs(p for p in files if not any(rule.search(p) for rule in patterns)):
            if not _go_generated(data, exclusions.get("generated", "strict")):
                _write_blob(directory, path, data)
                selected.append(path)
        if selected:
            version, goroot = subprocess.check_output(
                ["go", "env", "GOVERSION", "GOROOT"], env={**os.environ, "GOTOOLCHAIN": "local"}, text=True
            ).splitlines()
            if ".go-version" in tracked:
                expected = "go" + _staged_bytes(ctx, ".go-version").decode().strip()
                if version != expected:
                    raise Exit(f"Install {expected} from .go-version (found {version}).")
            gofmt = Path(goroot, "bin", "gofmt.exe" if os.name == "nt" else "gofmt")
            _run_files([str(gofmt), "-l", "-s"], selected, directory, list_differences=True)


def _shell_rc(path):
    return Path(path).name in {".shellcheckrc", "shellcheckrc"}


def _shell_script(path, data):
    if path.endswith((".sh", ".bash", ".bats", ".ksh")):
        return True
    return re.match(rb"^#![^\r\n]*\b(?:ba|da|k)?sh\b", data[:256])


@task(help={"base": "In CI, select paths changed between this commit and HEAD."})
def check_shellcheck(ctx, all_files=False, base=""):
    """Check selected scripts with their staged shebangs, ShellCheck directives and source context."""
    tracked = _tracked_paths(ctx)
    changed = set(_changed_paths(ctx, base))
    candidates = tracked if all_files or any(map(_shell_rc, changed)) else tracked & changed
    extensions = {"", ".in", ".sh", ".bash", ".bats", ".ksh"}
    files = sorted(p for p in candidates if Path(p).suffix in extensions and not _shell_rc(p))
    if not files:
        return
    with TemporaryDirectory() as directory:
        selected = []
        for path, contents in _staged_blobs(files):
            if _shell_script(path, contents):
                _write_blob(directory, path, contents)
                selected.append(path)
        if not selected:
            return
        rc_files = {p for p in tracked if _shell_rc(p)}
        external_sources = False
        for path, contents in _staged_blobs(rc_files):
            _write_blob(directory, path, contents)
            if any(Path(p).is_relative_to(Path(path).parent) for p in selected):
                external_sources |= bool(re.search(rb"(?m)^\s*external-sources\s*=\s*true\b", contents))
        if external_sources:
            # Source paths may cross directories and have arbitrary extensions.
            for path, contents in _staged_blobs(sorted(tracked - rc_files - set(selected))):
                _write_blob(directory, path, contents)
        _run_files(["shellcheck", "--severity=info", "-e", "SC2059", "-e", "SC2028"], selected, directory)


@task
def check_actionlint(ctx, all_files=False):
    """Validate workflows with the staged local action metadata, reusable workflows and configuration."""
    tracked = _tracked_paths(ctx)
    changed = set(_staged_paths(ctx))
    settings = {".github/actionlint.yaml", ".github/actionlint.yml"}
    workflows = {p for p in tracked if p.startswith(".github/workflows/") and p.endswith((".yml", ".yaml"))}
    action_dirs = {Path(p).parent for p in tracked if Path(p).name in {"action.yml", "action.yaml"}}
    expand = any(
        p.startswith(".github/actions/")
        or Path(p).name in {"action.yml", "action.yaml"}
        or action_dirs.intersection(Path(p).parents)
        for p in changed
    )
    selected = workflows if all_files or changed & settings or expand else workflows & changed
    if selected:
        with TemporaryDirectory() as directory:
            # actionlint discovers the project and enables local-action checks through this marker.
            Path(directory, ".git").mkdir()
            action_files = {p for p in tracked if action_dirs.intersection(Path(p).parents)}
            for path, data in _staged_blobs(workflows | action_files | (tracked & settings)):
                _write_blob(directory, path, data)
            _run_files(["actionlint", "-shellcheck=", "-pyflakes="], sorted(selected), directory)


@task
def check_set_x(ctx, all_files=False):
    """Check the staged shell, Dockerfile and YAML inputs for prohibited tracing."""
    tracked = _tracked_paths(ctx)
    files = tracked if all_files else tracked.intersection(_staged_paths(ctx))
    selected = sorted(
        path
        for path in files
        if path.endswith((".sh", "Dockerfile", ".yml")) or (path.endswith(".yaml") and ".pre-commit-config" not in path)
    )

    errors = []
    for file, data in _staged_blobs(selected):
        for nb, line in enumerate(data.decode("utf-8").splitlines(), 1):
            if re.search(r"set( +-[^ ])* +-[^ ]*(x|( +xtrace))", line):
                errors.append(
                    f"{color_message(file, 'magenta')}:{color_message(str(nb), 'green')}: {color_message(line.strip(), 'red')}"
                )

    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        print(color_message('error:', 'red'), 'No shell script should use "set -x"', file=sys.stderr)
        raise Exit(code=1)


@task
def check_release_json_newline(ctx):
    """Check the committed release metadata during CI."""
    if not _staged_bytes(ctx, "release.json").endswith(b"\n"):
        raise Exit("release.json requires a final newline.")
