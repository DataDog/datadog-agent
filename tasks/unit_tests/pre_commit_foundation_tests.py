class GitFixture(unittest.TestCase):
    def setUp(self):
        self.enterContext(chdir(self.enterContext(TemporaryDirectory())))
        self.ctx = Context()
        self.git("init", "-q")
        self.git("config", "core.autocrlf", "false")
        self.git("config", "core.hooksPath", ".git/empty-hooks")
        self.git("config", "commit.gpgsign", "false")
        self.git("config", "user.name", "Test")
        self.git("config", "user.email", "test@example.org")

    def git(self, *args):
        return subprocess.check_output(["git", *args], stderr=subprocess.PIPE)

    def stage(self, path, data):
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        self.git("add", "--", path)

    def assert_input_preserved(self, task, path, *, fails=True, **kwargs):
        index = Path(".git/index").read_bytes()
        contents = Path(path).read_bytes()
        if fails:
            with self.assertRaises(Exit):
                task(self.ctx, **kwargs)
        else:
            task(self.ctx, **kwargs)
        self.assertEqual(index, Path(".git/index").read_bytes())
        self.assertEqual(contents, Path(path).read_bytes())


class TestFoundation(GitFixture):
    def test_index_paths_include_deleted_and_both_sides_of_rename(self):
        name = "script with spaces.sh" if os.name == "nt" else "script\nwith spaces.sh"
        self.stage(name, b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        self.git("mv", "--", name, "renamed.sh")
        self.assertEqual(set(pre_commit._staged_paths(self.ctx)), {name, "renamed.sh"})
        self.assertEqual(pre_commit._tracked_paths(self.ctx), {"renamed.sh"})
        self.assertEqual(pre_commit._staged_bytes(self.ctx, "renamed.sh"), b"#!/bin/sh\n")

    def test_base_preserves_rewind_push_endpoint(self):
        self.stage("first.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        self.stage("second.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "second")
        before = self.git("rev-parse", "HEAD").decode().strip()
        self.git("checkout", "-q", "HEAD~1")
        self.assertEqual(pre_commit._changed_paths(self.ctx, before), ["second.sh"])

