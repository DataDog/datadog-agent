from tasks import pre_commit


class GitFixture(unittest.TestCase):
    def setUp(self):
        self.enterContext(chdir(self.enterContext(TemporaryDirectory())))
        self.ctx = Context()
        self.git("init", "-q")
        self.git("config", "core.autocrlf", "false")
        self.git("config", "core.hooksPath", ".git/empty-hooks")
        self.git("config", "commit.gpgsign", "false")
        self.git("config", "user.name", "Test")
        self.git("config", "user.email", "test@example.org")

    def git(self, *args):
        return subprocess.check_output(["git", *args], stderr=subprocess.PIPE)

    def stage(self, path, data):
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        self.git("add", "--", path)

    def assert_input_preserved(self, task, path, *, fails=True, **kwargs):
        index = Path(".git/index").read_bytes()
        contents = Path(path).read_bytes()
        if fails:
            with self.assertRaises(Exit):
                task(self.ctx, **kwargs)
        else:
            task(self.ctx, **kwargs)
        self.assertEqual(index, Path(".git/index").read_bytes())
        self.assertEqual(contents, Path(path).read_bytes())


class TestFoundation(GitFixture):
    def test_index_paths_include_deleted_and_both_sides_of_rename(self):
        name = "script with spaces.sh" if os.name == "nt" else "script\nwith spaces.sh"
        self.stage(name, b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        self.git("mv", "--", name, "renamed.sh")
        self.assertEqual(set(pre_commit._staged_paths(self.ctx)), {name, "renamed.sh"})
        self.assertEqual(pre_commit._tracked_paths(self.ctx), {"renamed.sh"})
        self.assertEqual(pre_commit._staged_bytes(self.ctx, "renamed.sh"), b"#!/bin/sh\n")

    def test_base_preserves_rewind_push_endpoint(self):
        self.stage("first.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        self.stage("second.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "second")
        before = self.git("rev-parse", "HEAD").decode().strip()
        self.git("checkout", "-q", "HEAD~1")
        self.assertEqual(pre_commit._changed_paths(self.ctx, before), ["second.sh"])

    @unittest.skipUnless(shutil.which("go"), "requires Go")
    def test_go_simplification_checks_the_index(self):
        path = "source with spaces.go"
        self.stage(".gitattributes", b"*.go text eol=crlf\n")
        bad = b"package p\n\nvar xs = []int{1}\nvar ys = xs[0:len(xs)]\n"
        self.stage(path, bad)
        Path(path).write_bytes(bad.replace(b"0:len(xs)", b"0:").replace(b"\n", b"\r\n"))
        self.assert_input_preserved(pre_commit.check_go_fmt, path)
        self.git("add", "--", path)
        self.assert_input_preserved(pre_commit.check_go_fmt, path, fails=False)

    @unittest.skipUnless(shutil.which("go"), "requires Go")
    def test_go_configuration_deletion_rechecks_existing_files(self):
        path = "old.go"
        self.stage(path, b"package x\nvar   y = 1\n")
        self.stage(".golangci.yml", b"formatters:\n  exclusions:\n    paths: ['old.go']\n")
        self.stage("types.pb.go", b"BROKEN\n")
        self.stage("z_gen.go", b"BROKEN\n")
        self.stage("generated.go", b"// Code generated by test. DO NOT EDIT.\npackage p\nvar   x = 2\n")
        pre_commit.check_go_fmt(self.ctx)
        self.git("commit", "-qm", "configured")
        self.git("rm", "-q", ".golangci.yml")
        Path(".golangci.yml").write_text("formatters:\n  exclusions:\n    paths: ['old.go']\n")
        self.assert_input_preserved(pre_commit.check_go_fmt, path)

    @unittest.skipUnless(shutil.which("shellcheck"), "requires ShellCheck")
    def test_shellcheck_reads_staged_rc_and_extensionless_shebang(self):
        path = "bin/named"
        self.stage(path, b"#!/bin/sh\n[[ -d test ]]\n")
        self.stage("bin/.shellcheckrc", b"shell=bash\n")
        Path("bin/.shellcheckrc").write_text("shell=sh\n")
        self.assert_input_preserved(pre_commit.check_shellcheck, path, fails=False)
        self.git("commit", "-qm", "bash")
        self.git("rm", "-q", "-f", "bin/.shellcheckrc")
        Path("bin/.shellcheckrc").write_text("shell=bash\n")
        self.assert_input_preserved(pre_commit.check_shellcheck, path)

    @unittest.skipUnless(shutil.which("shellcheck"), "requires ShellCheck")
    def test_shellcheck_uses_canonical_staged_sources(self):
        path = "nested/check.sh"
        self.stage(".gitattributes", b"* text eol=crlf\n")
        self.stage("nested/.shellcheckrc", b"source-path=SCRIPTDIR\nexternal-sources=true\n")
        self.stage("shared/input.inc", b"greeting=hello\n")
        self.stage(path, b'#!/bin/sh\n. ../shared/input.inc\nprintf "%s\\n" "$greeting"\n')
        Path("shared/input.inc").write_bytes(b"this broken (\r\n")
        self.assert_input_preserved(pre_commit.check_shellcheck, path, fails=False)

    @unittest.skipUnless(shutil.which("actionlint"), "requires actionlint")
    def test_action_change_validates_consuming_workflow_against_staged_metadata(self):
        path = ".github/workflows/check.yml"
        self.stage(
            path,
            b"on: push\njobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: ./.github/actions/check\n        with:\n          example: abc\n",
        )
        action = ".github/actions/check/action.yml"
        self.stage(".github/actions/check/check.js", b"")
        data = b"name: check\ndescription: check\ninputs:\n  example:\n    description: example\nruns:\n  using: node20\n  main: check.js\n"
        self.stage(action, data)
        self.assert_input_preserved(pre_commit.check_actionlint, path, fails=False)
        self.git("commit", "-qm", "valid workflow")
        self.stage(action, data.replace(b"example", b"other"))
        Path(action).write_bytes(data)
        self.assert_input_preserved(pre_commit.check_actionlint, action)

    def test_set_x_keeps_the_existing_file_and_pattern_policy(self):
        self.stage(".pre-commit-config.yaml", b"name: set -x\n")
        self.stage("commands.sh", b"set -v\n")
        pre_commit.check_set_x(self.ctx)
        self.stage("build.Dockerfile", b"RUN set -e -o xtrace\n")
        Path("build.Dockerfile").write_bytes(b"RUN echo safe\n")
        self.assert_input_preserved(pre_commit.check_set_x, "build.Dockerfile")

    def test_release_json_newline_is_read_only(self):
        self.stage("release.json", b"{}")
        Path("release.json").write_bytes(b"{}\n")
        self.assert_input_preserved(pre_commit.check_release_json_newline, "release.json")
