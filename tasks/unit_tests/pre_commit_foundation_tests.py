class TestChangedFiles(GitFixture):
    def setUp(self):
        super().setUp()
        if os.name == "nt":
            git_exec = Path(self.git("--exec-path").decode().strip())
            self.bash = str(git_exec.parents[2] / "bin/bash.exe")
        else:
            self.bash = shutil.which("bash")
        if not self.bash or not Path(self.bash).is_file():
            self.skipTest("requires Bash")

    def select(self, before, branch="main"):
        return subprocess.run(
            [
                self.bash,
                "-e",
                "-c",
                '. "$1"; printf "%s\\n" "${CHANGED_FILES_ARGS[@]}"',
                "_",
                CHANGED_FILES_SCRIPT.as_posix(),
            ],
            env={**os.environ, "COMPARE_TO_BRANCH": "main", "CI_COMMIT_BRANCH": branch, "CI_COMMIT_BEFORE_SHA": before},
            capture_output=True,
            text=True,
            check=True,
        )

    def rewound_runner(self):
        self.stage("first.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        first = self.git("rev-parse", "HEAD").decode().strip()
        self.stage("second.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "second")
        before = self.git("rev-parse", "HEAD").decode().strip()
        self.git("branch", "-M", "main")
        remote = Path(self.enterContext(TemporaryDirectory()))
        self.git("clone", "--bare", "--no-hardlinks", ".", str(remote))
        self.git("-C", str(remote), "config", "uploadpack.allowAnySHA1InWant", "true")
        self.git("-C", str(remote), "update-ref", "refs/heads/main", first)
        runner = Path(self.enterContext(TemporaryDirectory()))
        self.git("clone", remote.as_uri(), str(runner))
        self.enterContext(chdir(runner))
        self.git("config", "core.hooksPath", ".git/empty-hooks")
        self.git("config", "commit.gpgsign", "false")
        self.git("config", "user.name", "Test")
        self.git("config", "user.email", "test@example.org")
        self.assertNotEqual(subprocess.run(["git", "cat-file", "-e", before], capture_output=True).returncode, 0)
        return first, before

    def test_fetches_the_unreachable_previous_tip_on_a_fresh_runner(self):
        _, before = self.rewound_runner()
        self.assertEqual(self.select(before).stdout.splitlines(), ["--base", before])
        self.assertEqual(pre_commit._changed_paths(self.ctx, before), ["second.sh"])

    @unittest.skipUnless(shutil.which("shellcheck"), "requires ShellCheck")
    def test_unavailable_previous_tip_lints_the_last_commit_without_unchanged_baseline_errors(self):
        self.rewound_runner()
        self.stage("baseline.sh", b"#!/bin/sh\necho $1\n")
        self.git("commit", "-qm", "existing lint diagnostic")
        self.stage("changed.sh", b"#!/bin/sh\nprintf '%s\\n' hello\n")
        self.git("commit", "-qm", "clean script change")
        result = self.select("f" * 40)
        self.assertEqual(result.stdout.splitlines(), ["--base", "HEAD^"])
        self.assertIn("may omit earlier changes", result.stderr)
        with self.assertRaises(Exit):
            pre_commit.check_shellcheck(self.ctx, all_files=True)
        self.assert_input_preserved(pre_commit.check_shellcheck, "changed.sh", fails=False, base="HEAD^")

    def test_root_commit_without_a_previous_tip_checks_all_files(self):
        self.stage("first.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "first")
        self.assertEqual(self.select("0" * 40).stdout.splitlines(), ["--all-files"])

    def test_feature_branch_uses_the_merge_base(self):
        first, _ = self.rewound_runner()
        self.git("checkout", "-qb", "feature")
        self.stage("feature.sh", b"#!/bin/sh\n")
        self.git("commit", "-qm", "feature")
        self.assertEqual(self.select("0" * 40, branch="feature").stdout.splitlines(), ["--base", first])
