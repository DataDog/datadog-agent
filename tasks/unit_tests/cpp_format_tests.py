"""Check C/C++ formatting scope and native clang-format configuration lookup."""

import importlib.util
import shutil
import subprocess
import sys
import tempfile
import unittest
from contextlib import chdir
from pathlib import Path
from unittest.mock import patch

REPO = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("hooks", REPO / "tasks/hooks.py")
hooks = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(hooks)


class TestCppFormat(unittest.TestCase):
    def setUp(self):
        self.root = Path(self.enterContext(tempfile.TemporaryDirectory())) / "repo"
        self.root.mkdir()
        self.enterContext(patch.object(hooks, "ROOT", self.root))
        self.enterContext(chdir(self.root))
        self.git("init", "--template=")

    def git(self, *args, data=None):
        return subprocess.run(["git", *args], cwd=self.root, input=data, capture_output=True, check=True).stdout

    def write(self, path, contents):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(contents)

    def validate(self, *paths):
        with patch.object(sys, "argv", ["hooks.py", "clang-format", *paths]):
            return hooks.main()

    def test_configuration_changes_select_all_eligible_tracked_sources(self):
        expected = ["a.c", "a.cc", "a.cpp", "a.cxx", "a.h", "a.hh", "a.hpp", "a.hxx", "nested/driver.c"]
        for path in [*expected, "deps/a.h", "third_party/a.c", "vendor/a.cpp", "example.cu", "example.m"]:
            self.write(path, b"int value;\n")
        self.git("add", ".")
        self.write("untracked.c", b"int value;\n")

        for config in [".clang-format", "nested/_clang-format", "nested/.clang-format-ignore"]:
            with self.subTest(config=config):
                self.assertEqual(hooks.selected_files("clang-format", [config]), expected)
        self.assertEqual(hooks.selected_files("clang-format", ["nested/driver.c", "deps/a.h"]), ["nested/driver.c"])

    def test_generated_headers_are_excluded_without_hiding_ordinary_code(self):
        examples = {
            "cbindgen.h": b"/* Warning, this file is autogenerated by cbindgen. Don't modify this manually. */\n",
            "helpers.h": b"/* This is auto-generated file. See bpf_doc.py for details. */\n",
            "vmlinux.h": b"#ifndef __VMLINUX_H__\r\n#define __VMLINUX_H__\r\n",
            "ordinary.h": b"/* This function uses auto-generated input. */\nint value;\n",
            "fallback.h": b"#ifndef __VMLINUX_H__\nstruct fallback;\n#endif\n",
        }
        for path, contents in examples.items():
            self.write(path, contents)
        self.assertEqual(hooks.selected_files("clang-format", [*examples, "deleted.h"]), ["fallback.h", "ordinary.h"])

    @unittest.skipUnless(shutil.which("clang-format"), "clang-format is required")
    def test_git_normalized_input_uses_its_own_style_and_ignore_files(self):
        files = {
            ".gitattributes": b"*.c text eol=lf\n",
            ".gitignore": b"nested/.clang-format\nnested/.clang-format-ignore\n",
            ".clang-format": b"BasedOnStyle: LLVM\nPointerAlignment: Right\n",
            "nested/.clang-format": b"BasedOnStyle: LLVM\nPointerAlignment: Left\nLineEnding: LF\n",
            "nested/.clang-format-ignore": b"ignored.c\n",
            "nested/formatted.c": b"int* first;\r\nint* second;\n",
            "nested/ignored.c": b"int  * first;\r\nint* second;\n",
            "nested/unformatted.c": b"int  * first;\r\nint* second;\n",
            "nested/whitespace.c": b" \t\r\n",
            "nested/unsupported.c": b"\xff\xfe1\x002\x00\r\n",
            "broken/.clang-format": b"NoSuchFormattingOption: true\n",
            "broken/source.c": b"int first;\r\nint second;\n",
            "broken/blank.c": b"\r\n",
        }
        for path, contents in files.items():
            self.write(path, contents)
        self.git("-c", "core.safecrlf=false", "add", ".")
        index = self.git("ls-files", "--stage", "-z")
        self.assertEqual(self.validate("nested/formatted.c", "nested/ignored.c"), 0)
        for path in [
            "nested/unformatted.c",
            "nested/whitespace.c",
            "nested/unsupported.c",
            "broken/source.c",
            "broken/blank.c",
        ]:
            with self.subTest(path=path):
                self.assertEqual(self.validate(path), 1)
        self.assertEqual(self.git("ls-files", "--stage", "-z"), index)
        for path, contents in files.items():
            with self.subTest(path=path):
                self.assertEqual((self.root / path).read_bytes(), contents)

    @unittest.skipUnless(shutil.which("clang-format"), "clang-format is required")
    def test_normalized_inputs_use_original_paths_for_ancestor_ignore_rules(self):
        self.write(".gitattributes", b"*.c text eol=lf\n")
        self.write(".clang-format", b"BasedOnStyle: LLVM\n")
        for name in ["ancestor.c", "absolute.c"]:
            self.write(name, b"int   first;\r\nint second;\n")
        self.git("-c", "core.safecrlf=false", "add", ".")
        absolute = (self.root / "absolute.c").as_posix()
        (self.root.parent / ".clang-format-ignore").write_text(f"repo/ancestor.c\n{absolute}\n", encoding="utf-8")

        self.assertEqual(self.validate("ancestor.c"), 0)
        # Absolute patterns with a Windows drive prefix have platform-specific
        # semantics. Use the native positional result from this checkout.
        native = subprocess.run(
            ["clang-format", "--dry-run", "--Werror", "--style=file", "./absolute.c"],
            cwd=self.root,
            capture_output=True,
        )
        self.assertEqual(self.validate("absolute.c"), native.returncode)

    @unittest.skipUnless(shutil.which("clang-format"), "clang-format is required")
    def test_formatter_resolves_parent_and_shadowed_configuration(self):
        self.write(".clang-format", b"<<<<<<< ours\nBasedOnStyle: Google\n=======\n>>>>>>> theirs\n")
        self.write("nested/.clang-format", b"BasedOnStyle: Google\n")
        self.write("a.c", b"int value;\n")
        self.write("nested/a.c", b"int nested;\n")
        self.git("add", ".")
        oid = self.git("rev-parse", ":.clang-format").decode().strip()
        self.git("update-index", "--force-remove", ".clang-format")
        stages = f"100644 {oid} 1\t.clang-format\n100644 {oid} 2\t.clang-format\n"
        self.git("update-index", "--index-info", data=stages.encode())

        self.assertEqual(self.validate("nested/a.c"), 0)
        self.assertEqual(self.validate("a.c"), 1)
        self.write("nested/.clang-format", b"BasedOnStyle: InheritParentConfig\n")
        self.assertEqual(self.validate("nested/a.c"), 1)


if __name__ == "__main__":
    unittest.main()
