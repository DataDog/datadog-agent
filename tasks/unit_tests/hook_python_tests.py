import io
import os
import shutil
import subprocess
import sys
import unittest
from pathlib import Path
from unittest.mock import patch

from tasks import linter
from tasks.libs.types.copyright import COPYRIGHT_HEADER, CopyrightLinter
from tasks.unit_tests.pre_commit_foundation_tests import GitFixture

REPOSITORY = Path(__file__).resolve().parents[2]
RULES = 'tasks/libs/types/copyright.py'


class TestHookPython(GitFixture):
    @unittest.skipUnless(shutil.which('ruff'), 'requires Ruff')
    def test_ruff_checks_canonical_index_without_fixing(self):
        self.stage('.gitattributes', b'*.py text eol=crlf\n')
        self.stage('file with spaces.py', b'x=1\n')
        Path('file with spaces.py').write_bytes(b'x = 1\r\n')
        self.assert_input_preserved(linter.python, 'file with spaces.py', only_staged_files=True)
        self.git('add', '--', 'file with spaces.py')
        self.assert_input_preserved(linter.python, 'file with spaces.py', only_staged_files=True, fails=False)

    @unittest.skipUnless(shutil.which('ruff'), 'requires Ruff')
    def test_ruff_lint_does_not_fix_unused_imports(self):
        self.stage('pyproject.toml', b'[tool.ruff.lint]\nselect = ["F"]\n')
        self.stage('source.py', b'import os\n')
        Path('source.py').write_bytes(b'')
        self.assert_input_preserved(linter.python, 'source.py', only_staged_files=True)

    @unittest.skipUnless(shutil.which('ruff'), 'requires Ruff')
    def test_deleted_ruff_configuration_expands_scope_and_ignores_unstaged_copy(self):
        config = b'[tool.ruff]\nexclude = ["old.py"]\n'
        self.stage('pyproject.toml', config)
        self.stage('old.py', b'x=1\n')
        linter.python(self.ctx, only_staged_files=True)
        self.git('commit', '-qm', 'configured')
        self.git('rm', '-q', 'pyproject.toml')
        Path('pyproject.toml').write_bytes(config)
        self.assert_input_preserved(linter.python, 'old.py', only_staged_files=True)

    @unittest.skipUnless(shutil.which('ruff'), 'requires Ruff')
    def test_ruff_uses_staged_native_ignore_files(self):
        self.stage('ignored.py', b'x=1\n')
        self.stage('.gitignore', b'ignored.py\n')
        Path('.gitignore').write_bytes(b'')
        self.assert_input_preserved(linter.python, 'ignored.py', only_staged_files=True, fails=False)

    @unittest.skipUnless(shutil.which('ruff'), 'requires Ruff')
    def test_ruff_preserves_unchanged_import_context_without_linting_it(self):
        self.stage('pyproject.toml', (REPOSITORY / 'pyproject.toml').read_bytes())
        self.stage('localmod.py', b'unchanged=1\n')
        self.git('commit', '-qm', 'local module')
        self.stage('source.py', b'import requests\n\nimport localmod\n\nrequests.get(localmod.unchanged)\n')
        self.assert_input_preserved(linter.python, 'source.py', only_staged_files=True, fails=False)

    @unittest.skipUnless(shutil.which('ruff') and os.name != 'nt', 'requires Ruff and POSIX filenames')
    def test_ruff_handles_newline_filenames(self):
        path = 'source\nwith newline.py'
        self.stage(path, b'value=1\n')
        self.assert_input_preserved(linter.python, path, only_staged_files=True)

    def test_copyright_reads_index_and_preserves_bsd_and_generated_exclusions(self):
        self.stage(RULES, (REPOSITORY / RULES).read_bytes())
        self.stage('source.go', b'package example\n')
        Path('source.go').write_bytes(COPYRIGHT_HEADER.encode() + b'\r\n\r\npackage example\r\n')
        self.assert_input_preserved(linter.copyrights, 'source.go', only_staged_files=True)
        self.git('add', '--', 'source.go')
        bsd = COPYRIGHT_HEADER.replace('Apache License Version 2.0', 'BSD 3-Clause License')
        self.stage('cmd/secret-generic-connector/main.go', bsd.encode() + b'\n\npackage main\n')
        self.stage('generated.go', b'// Code generated by example. DO NOT EDIT.\npackage example\n')
        self.stage('vendor/example.go', b'package example\n')
        self.assert_input_preserved(linter.copyrights, 'source.go', only_staged_files=True, fails=False)

    def test_copyright_rules_deletion_expands_scope(self):
        self.stage('old.go', b'package example\n')
        self.stage('tasks/libs/types/copyright.py', b'')
        self.git('commit', '-qm', 'old files')
        self.git('rm', '-q', 'tasks/libs/types/copyright.py')
        self.assert_input_preserved(linter.copyrights, 'old.go', only_staged_files=True)

    def test_copyright_uses_staged_policy_instead_of_working_copy(self):
        rules = (REPOSITORY / RULES).read_bytes()
        permissive = rules + b"\nCOMPILED_HEADER_EXCLUSION_REGEX.append(re.compile('^package '))\n"
        self.stage(RULES, permissive)
        Path(RULES).write_bytes(rules)
        self.stage('source.go', b'package example\n')
        self.assert_input_preserved(linter.copyrights, 'source.go', only_staged_files=True, fails=False)
        self.stage(RULES, rules)
        Path(RULES).write_bytes(permissive)
        self.assert_input_preserved(linter.copyrights, 'source.go', only_staged_files=True)

    def test_copyright_explicit_staged_repair_and_dry_run(self):
        self.stage(RULES, (REPOSITORY / RULES).read_bytes())
        self.stage('source.go', b'package example\n')
        self.assert_input_preserved(
            linter.copyrights, 'source.go', only_staged_files=True, fix=True, dry_run=True, fails=False
        )
        linter.copyrights(self.ctx, only_staged_files=True, fix=True)
        self.assertTrue(Path('source.go').read_text().startswith(COPYRIGHT_HEADER))
        self.assertEqual(self.git('show', ':source.go'), b'package example\n')

    def test_copyright_explicit_repair_does_not_expand_or_repair_missing_work_files(self):
        rules = (REPOSITORY / RULES).read_bytes()
        self.stage(RULES, rules)
        self.stage('old.go', b'package example\n')
        self.git('commit', '-qm', 'existing files')
        self.stage(RULES, rules + b'\n# Policy comment.\n')
        self.assert_input_preserved(linter.copyrights, 'old.go', only_staged_files=True, fix=True, fails=False)
        self.assert_input_preserved(linter.copyrights, 'old.go', only_staged_files=True)
        self.stage('source.go', b'package example\n')
        Path('source.go').unlink()
        linter.copyrights(self.ctx, only_staged_files=True, fix=True)
        self.assertFalse(Path('source.go').exists())
        self.assertEqual(self.git('show', ':source.go'), b'package example\n')

    def test_staged_policy_works_without_an_importable_working_copy(self):
        shutil.copytree(REPOSITORY / 'tasks', 'tasks', ignore=shutil.ignore_patterns('__pycache__', 'unit_tests'))
        self.stage(RULES, (REPOSITORY / RULES).read_bytes())
        self.stage('source.go', COPYRIGHT_HEADER.encode() + b'\n\npackage example\n')
        Path(RULES).unlink()
        result = subprocess.run(
            [sys.executable, '-m', 'invoke', 'linter.copyrights', '--only-staged-files'],
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse(Path(RULES).exists())

    def test_copyright_repository_lookup_uses_native_path(self):
        with (
            patch(
                'tasks.libs.types.copyright.subprocess.check_output', return_value=os.fsencode('/r\u00e9po\n')
            ) as lookup,
            patch('sys.stdout', new=io.StringIO()),
        ):
            self.assertEqual(CopyrightLinter._get_repo_dir().as_posix(), '/r\u00e9po')
        self.assertIsInstance(lookup.call_args.kwargs['cwd'], Path)

    @unittest.skipIf(os.name == 'nt', 'requires POSIX filesystem bytes')
    def test_copyright_repository_lookup_preserves_filesystem_bytes(self):
        with (
            patch('tasks.libs.types.copyright.subprocess.check_output', return_value=b'/repo-\xff\n'),
            patch('sys.stdout', new=io.StringIO()),
        ):
            self.assertEqual(os.fsencode(CopyrightLinter._get_repo_dir().as_posix()), b'/repo-\xff')
