"""
Generates the build-time CODEOWNERS table used to tag errortracking events with the owning team.

The table is a Go source file in the agent telemetry component. A second file lists, for
every CODEOWNERS rule, a representative path and the owner the Python CODEOWNERS parser
resolves for it. The Go matcher test replays that file to prove both implementations agree.
"""

from __future__ import annotations

import difflib
import os

from invoke import task
from invoke.exceptions import Exit

from tasks.libs.owners.parsing import read_owners

OWNERS_FILE = ".github/CODEOWNERS"
IMPL_DIR = "comp/core/agenttelemetry/impl"
GENERATED_GO = f"{IMPL_DIR}/errortracking_owners_gen.go"
PARITY_GOLDEN = f"{IMPL_DIR}/testdata/errortracking_owners_parity.tsv"

# Real paths replayed against the Go matcher on top of the synthesized per-rule paths.
SAMPLE_PATHS = [
    "cmd/agent/main.go",
    "cmd/trace-agent/main.go",
    "comp/core/agenttelemetry/impl/errortracking_sender.go",
    "comp/core/config/impl/config.go",
    "comp/logs/agent/agent.go",
    "pkg/collector/check/loader.go",
    "pkg/collector/corechecks/system/cpu/cpu_windows.go",
    "pkg/logs/launchers/file/launcher.go",
    "pkg/logs/sender/sender.go",
    "pkg/trace/agent/agent.go",
    "pkg/trace/api/loader/listeners.go",
    "pkg/trace/api/otlp.go",
    "pkg/util/log/log.go",
    "pkg/util/kubernetes/apiserver/apiserver.go",
    "cmd/installer/subcommands/daemon/main_windows.go",
    "README.md",
    "go.mod",
    "tasks/errortracking_owners.py",
]

_HEADER = """// Unless explicitly stated otherwise all files in this repository are licensed
// under the Apache License Version 2.0.
// This product includes software developed at Datadog (https://www.datadoghq.com/).
// Copyright 2026-present Datadog, Inc.

// Code generated by `dda inv errortracking-owners.generate` from .github/CODEOWNERS. DO NOT EDIT.

package agenttelemetryimpl
"""

_TEAM_PREFIX = "@datadog/"
_NO_OWNER = "-"


def _primary_team(owners: list[tuple[str, str]]) -> str:
    """Slug of the first team owner of a CODEOWNERS row, or '' when the row names no team."""
    for kind, owner in owners:
        if kind == "TEAM" and owner.casefold().startswith(_TEAM_PREFIX):
            return owner.casefold()[len(_TEAM_PREFIX) :]
    return ""


def _rules(owners_file: str) -> list[tuple[str, str]]:
    """(pattern, primary team slug) for every CODEOWNERS row, in file order."""
    parsed = read_owners(owners_file)
    rules = []
    for _, pattern, owners, _, _ in reversed(parsed.paths):
        if any(c in pattern for c in "\\[`\n\t "):
            raise Exit(f"CODEOWNERS pattern {pattern!r} uses syntax the errortracking matcher does not support")
        rules.append((pattern, _primary_team(owners)))
    return rules


def render_go(rules: list[tuple[str, str]]) -> str:
    teams = sorted({team for _, team in rules if team})
    team_index = {team: str(i) for i, team in enumerate(teams)}
    rule_lines = "\n".join(f"{team_index.get(team, _NO_OWNER)} {pattern}" for pattern, team in rules)
    return (
        f"{_HEADER}\n"
        "// ownerTeams lists the team slugs, one per line; a rule refers to a team by its line number.\n"
        f"const ownerTeams = `{chr(10).join(teams)}`\n\n"
        "// ownerRules lists the CODEOWNERS rows in file order (the last match wins) as\n"
        '// "<team line number or ->" followed by a space and the pattern.\n'
        f"const ownerRules = `{rule_lines}`\n"
    )


def _synthesize(pattern: str) -> str:
    """A path the pattern matches, built by filling in each wildcard."""
    slash = pattern.find("/")
    anchored = slash > -1 and slash != len(pattern) - 1
    segments = []
    for segment in pattern.strip("/").split("/"):
        segments.append("a/b" if segment == "**" else segment.replace("*", "x").replace("?", "x"))
    path = "/".join(segments)
    if not anchored:
        path = "sub/" + path
    if "." not in segments[-1]:
        path += "/z.go"
    return path


def render_golden(owners_file: str, rules: list[tuple[str, str]]) -> str:
    parsed = read_owners(owners_file)  # cached, shares the parse done by _rules
    paths = sorted({_synthesize(pattern) for pattern, _ in rules} | set(SAMPLE_PATHS))
    return "".join(f"{path}\t{_primary_team(parsed.of(path))}\n" for path in paths)


def _check(path: str, expected: str) -> None:
    try:
        with open(path) as f:
            actual = f.read()
    except FileNotFoundError:
        actual = ""
    if actual != expected:
        diff = "".join(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True), path, "expected", n=0))
        raise Exit(
            f"{path} is not up to date, please run `dda inv errortracking-owners.generate`\n{diff[:2000]}",
            code=1,
        )


@task
def generate(_, check=False, owners_file=OWNERS_FILE):
    """
    Regenerate the errortracking team table and its parity file from CODEOWNERS.

    With --check, regenerate in memory and fail if the checked-in files differ.
    """
    rules = _rules(owners_file)
    outputs = {
        GENERATED_GO: render_go(rules),
        PARITY_GOLDEN: render_golden(owners_file, rules),
    }
    for path, content in outputs.items():
        if check:
            _check(path, content)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(content)
