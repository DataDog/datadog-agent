// Writer accepts only already-sanitized samples from the live coordinator.
// The absence of COMPLETE makes failed or interrupted captures non-replayable.
type Writer struct {
	mu        sync.Mutex
	directory string
	manifest  Manifest
	closed    bool
}

func NewWriter(directory string, manifest Manifest) (*Writer, error) {
	if !validBuild(manifest.CaptureTool) || !opaqueIDPattern.MatchString(manifest.SessionID) {
		return nil, errors.New("capture writer requires a valid tool build and session identity")
	}
	if err := os.Mkdir(directory, 0700); err != nil {
		return nil, fmt.Errorf("capture requires a new output directory: %w", err)
	}
	manifest.SchemaVersion = SchemaVersion
	manifest.SanitizerVersion = SanitizerVersion
	manifest.Complete = false
	manifest.Samples = nil
	manifest.Files = map[string]string{}
	manifest.Producers = cloneProducers(manifest.Producers)
	manifest.MetricCadences = maps.Clone(manifest.MetricCadences)
	return &Writer{directory: directory, manifest: manifest}, nil
}

// Append preserves a logical cycle's producer identity, sequence, and ordered
// chunks. Filenames are always generated by the writer.
func (w *Writer) Append(ref SampleRef, sanitized any) error {
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.closed {
		return errors.New("bundle writer is closed")
	}
	if !opaqueIDPattern.MatchString(ref.ProducerID) || ref.CycleID == 0 || ref.Sequence == 0 || ref.Offset < 0 || ref.ChunkCount <= 0 || ref.ChunkIndex < 0 || ref.ChunkIndex >= ref.ChunkCount {
		return errors.New("capture sample requires producer and complete cycle identity")
	}
	data, err := json.Marshal(sanitized)
	if err != nil {
		return errors.New("cannot encode sanitized sample")
	}
	prefix := fmt.Sprintf("sample-%06d", len(w.manifest.Samples))
	ref.File = prefix + ".json"
	if err := w.write(ref.File, data); err != nil {
		return err
	}
	w.manifest.Samples = append(w.manifest.Samples, ref)
	return nil
}

func (w *Writer) write(name string, data []byte) error {
	if len(data) > maxFileBytes {
		return errors.New("sanitized bundle file exceeds size limit")
	}
	if err := writeExclusive(filepath.Join(w.directory, name), data); err != nil {
		return err
	}
	w.manifest.Files[name] = schema.Digest(data)
	return nil
}

func writeExclusive(path string, data []byte) error {
	_, err := writeExclusiveOwned(path, data)
	return err
}

// The ownership result remains true after write, sync, or close failures, so a
// caller can remove its incomplete file without touching a pre-existing file.
func writeExclusiveOwned(path string, data []byte) (bool, error) {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return false, err
	}
	_, writeErr := f.Write(data)
	syncErr := f.Sync()
	closeErr := f.Close()
	if writeErr != nil {
		return true, writeErr
	}
	if syncErr != nil {
		return true, syncErr
	}
	if closeErr != nil {
		return true, closeErr
	}
	return true, nil
}

func cloneProducers(producers []Producer) []Producer {
	owned := slices.Clone(producers)
	for i := range owned {
		owned[i].Streams = slices.Clone(owned[i].Streams)
	}
	return owned
}

// SetProducers supplies final acknowledged boundaries after every producer has
// disarmed and drained. Complete validates them against all persisted samples.
func (w *Writer) SetProducers(producers []Producer) error {
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.closed {
		return errors.New("bundle writer is closed")
	}
	w.manifest.Producers = cloneProducers(producers)
	return nil
}

// Complete writes the manifest followed by its completion marker. A load check
// verifies coverage and all bytes before completion can be reported to a caller.
func (w *Writer) Complete(duration time.Duration, profile schema.Profile, cadences map[schema.Stream]time.Duration) (*Loaded, error) {
	return w.CompleteContext(context.Background(), duration, profile, cadences)
}

// CompleteContext revokes the completion marker if final validation fails or
// cancellation arrives while the manifest and its contents are being checked.
func (w *Writer) CompleteContext(ctx context.Context, duration time.Duration, profile schema.Profile, cadences map[schema.Stream]time.Duration) (loaded *Loaded, err error) {
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.closed {
		return nil, errors.New("bundle writer is closed")
	}
	w.closed = true
	markerCreated := false
	defer func() {
		if recover() != nil {
			err = errors.New("bundle finalization failed")
		}
		if err != nil {
			loaded = nil
			if markerCreated {
				if removeErr := os.Remove(filepath.Join(w.directory, "COMPLETE")); removeErr != nil && !os.IsNotExist(removeErr) {
					err = errors.Join(err, removeErr)
				}
			}
		}
	}()
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	w.manifest.Duration = duration
	profile.Streams = slices.Clone(profile.Streams)
	profile.MetricNames = slices.Clone(profile.MetricNames)
	profile.ProcessNames = slices.Clone(profile.ProcessNames)
	profile.SoftwareNames = slices.Clone(profile.SoftwareNames)
	profile.ConnectionSelectors = slices.Clone(profile.ConnectionSelectors)
	w.manifest.Profile = profile
	w.manifest.Cadences = maps.Clone(cadences)
	w.manifest.Complete = true
	if _, err := w.manifest.validateProvenance(); err != nil {
		return nil, err
	}
	data, err := json.MarshalIndent(w.manifest, "", "  ")
	if err != nil {
		return nil, err
	}
	if len(data) > maxManifestBytes {
		return nil, errors.New("capture manifest exceeds size limit")
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	// These files are not included in the manifest's own file inventory.
	if err := writeExclusive(filepath.Join(w.directory, "manifest.json"), data); err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	markerCreated, err = writeExclusiveOwned(filepath.Join(w.directory, "COMPLETE"), []byte(schema.Digest(data)+"\n"))
	if err != nil {
		return nil, err
	}
	loaded, err = Load(w.directory, w.manifest.CaptureTool.Commit)
	if err == nil {
		err = ctx.Err()
	}
	return loaded, err
}
