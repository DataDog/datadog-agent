func TestRepoPath(t *testing.T) {
	tests := []struct {
		name   string
		frame  stackFrame
		want   string
		wantOK bool
	}{
		{
			name:   "trimmed path",
			frame:  stackFrame{"github.com/DataDog/datadog-agent/pkg/logs/sender.(*S).Send", "github.com/DataDog/datadog-agent/pkg/logs/sender/sender.go"},
			want:   "pkg/logs/sender/sender.go",
			wantOK: true,
		},
		{
			name:   "gopath checkout",
			frame:  stackFrame{"github.com/DataDog/datadog-agent/pkg/trace/agent.run", "/go/src/github.com/DataDog/datadog-agent/pkg/trace/agent/agent.go"},
			want:   "pkg/trace/agent/agent.go",
			wantOK: true,
		},
		{
			name:   "absolute path outside the module path uses the function package",
			frame:  stackFrame{"github.com/DataDog/datadog-agent/pkg/collector/check.(*Loader).Load", "/Users/dev/repos/datadog-agent/pkg/collector/check/loader.go"},
			want:   "pkg/collector/check/loader.go",
			wantOK: true,
		},
		{
			name:   "generic function and closure",
			frame:  stackFrame{"github.com/DataDog/datadog-agent/pkg/util/retry.Do[...].func1", "/src/pkg/util/retry/retry.go"},
			want:   "pkg/util/retry/retry.go",
			wantOK: true,
		},
		{
			name:   "module cache copy of the repository module uses the function package",
			frame:  stackFrame{"github.com/DataDog/datadog-agent/pkg/version.Agent", "/go/pkg/mod/github.com/!data!dog/datadog-agent/pkg/version@v0.5.0/version.go"},
			want:   "pkg/version/version.go",
			wantOK: true,
		},
		{
			name:   "package main with an absolute path outside the module path",
			frame:  stackFrame{"main.run", "/Users/dev/repos/datadog-agent/cmd/agent/main.go"},
			want:   "cmd/agent/main.go",
			wantOK: true,
		},
		{
			name:  "package main without a cmd directory",
			frame: stackFrame{"main.run", "/tmp/other/main.go"},
		},
		{
			name:  "standard library",
			frame: stackFrame{"runtime.gopanic", "/usr/local/go/src/runtime/panic.go"},
		},
		{
			name:  "third party",
			frame: stackFrame{"github.com/spf13/cobra.(*Command).Execute", "/go/pkg/mod/github.com/spf13/cobra@v1.8.0/command.go"},
		},
		{
			name:  "generated wrapper without a Go file",
			frame: stackFrame{"github.com/DataDog/datadog-agent/pkg/logs.(*T).M", "<autogenerated>"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, ok := repoPath(tt.frame)
			assert.Equal(t, tt.wantOK, ok)
			assert.Equal(t, tt.want, got)
		})
	}
}

func TestOwningTeam(t *testing.T) {
	rules := parseOwnerRules("logs\nruntimes\napm\nutil\ncontainers", `0 /pkg/logs/
1 /pkg/collector/
2 /pkg/trace/
3 /pkg/util/
4 /pkg/util/kubernetes/
3 /pkg/util/log/
- /pkg/orphan/`)

	// frame builds a symbolized frame whose package matches its directory.
	frame := func(repoFile string) stackFrame {
		dir := repoFile[:strings.LastIndex(repoFile, "/")]
		return stackFrame{function: repoModulePrefix + dir + ".F", file: "/build/" + repoFile}
	}
	std := stackFrame{function: "runtime.gopanic", file: "/usr/local/go/src/runtime/panic.go"}
	slog := stackFrame{function: "log/slog.(*Logger).Error", file: "/usr/local/go/src/log/slog/logger.go"}
	thirdParty := stackFrame{function: "github.com/spf13/cobra.(*Command).Execute", file: "/go/pkg/mod/github.com/spf13/cobra@v1.8.0/command.go"}

	tests := []struct {
		name   string
		frames []stackFrame
		want   string
	}{
		{
			name:   "first in-repo frame owns the error",
			frames: []stackFrame{frame("pkg/logs/sender/sender.go"), frame("pkg/collector/check/loader.go")},
			want:   "logs",
		},
		{
			name: "logging plumbing and the standard library are skipped",
			frames: []stackFrame{
				frame("pkg/util/log/log.go"), frame("comp/core/log/impl/logger.go"),
				frame("comp/core/agenttelemetry/impl/errortracking_sender.go"),
				slog, std, frame("pkg/trace/agent/agent.go"),
			},
			want: "apm",
		},
		{
			name:   "shared helper walks down to its caller",
			frames: []stackFrame{frame("pkg/util/filesystem/file.go"), frame("pkg/collector/check/loader.go"), frame("pkg/logs/sender/sender.go")},
			want:   "runtimes",
		},
		{
			name:   "walk down passes third party frames between helper and caller",
			frames: []stackFrame{frame("pkg/util/retry/retry.go"), thirdParty, frame("pkg/logs/sender/sender.go")},
			want:   "logs",
		},
		{
			name:   "shared helper with no other in-repo frame keeps its own owner",
			frames: []stackFrame{frame("pkg/util/filesystem/file.go"), thirdParty, std},
			want:   "util",
		},
		{
			name:   "package under a helper prefix with its own owner keeps it",
			frames: []stackFrame{frame("pkg/util/kubernetes/client.go"), frame("pkg/logs/sender/sender.go")},
			want:   "containers",
		},
		{
			name:   "collector frames never walk down",
			frames: []stackFrame{frame("pkg/collector/check/loader.go"), frame("pkg/logs/sender/sender.go")},
			want:   "runtimes",
		},
		{
			name:   "frame without an owner is passed over",
			frames: []stackFrame{frame("pkg/orphan/x.go"), frame("pkg/logs/sender/sender.go")},
			want:   "logs",
		},
		{
			name:   "only unowned in-repo frames give no team",
			frames: []stackFrame{frame("pkg/orphan/x.go"), frame("pkg/orphan/y.go")},
			want:   "",
		},
		{
			name:   "only third party and standard library frames give no team",
			frames: []stackFrame{std, slog, thirdParty},
			want:   "",
		},
		{
			name:   "empty stack",
			frames: nil,
			want:   "",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, owningTeam(rules, tt.frames))
		})
	}
}

func TestTeamTag(t *testing.T) {
	// A program counter inside an in-repo function outside the plumbing
	// packages; the function lives in a package owned in CODEOWNERS.
	// CallersFrames treats counters as return addresses, so step past the entry.
	var e errortracking.ErrorLog
	e.PCs[0] = reflect.ValueOf(agentversion.Agent).Pointer() + 1
	e.PCsLen = 1

	want := ownerOfPath(codeOwnersRules(), "pkg/version/version.go")
	require.NotEmpty(t, want)
	assert.Equal(t, ",team:"+want, teamTag(e))
	assert.Equal(t, "", teamTag(errortracking.ErrorLog{}), "no stack gives no tag")

	e.Time = time.Unix(1, 0)
	assert.Contains(t, enrichErrorLog(e).Tags, ",team:"+want)
}
