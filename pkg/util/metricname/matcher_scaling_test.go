// Scaling and allocation regression tests for the metric filter list matcher.
//
// Ported from the `metric_filterlist_scaling` experiment in smp-playground
// (experiments/regression/agent/metric_filterlist_scaling/), which answered
// "what happens to the Agent when metric_filterlist grows from 10k to 100k
// entries?". That harness lived outside this repo and copied its benchmark file
// in temporarily; the findings it established are load-bearing for the filter
// list, so they are pinned here as assertions that run in CI.
//
// The findings this file guards, from that experiment:
//
//   - Matcher.Test is allocation-free. Measured 0 B/op, 0 allocs/op at every
//     size from 10k to 100k. This is the single most important invariant: Test
//     runs on every DogStatsD sample (comp/dogstatsd/server/impl/enrich.go) and
//     on every flushed series (pkg/aggregator/time_sampler.go).
//   - Lookup cost is flat, because matching is an O(log n) binary search over a
//     sorted slice: p50 51 ns at 10k, 58 ns at 100k; p99 165 ns and 173 ns.
//   - Construction is a single allocation of ~16 B/entry, because only string
//     headers are copied, never the name bytes.
//   - Compiled-matcher memory is independent of name length: 16.1 B/entry at
//     both 34 and 88 character names.
//   - Comparison depth is free. Moving the diverging characters from position
//     33 to position 87 ("tail" vs "deep" layout below) was unmeasurable.
//
// Names in the fixtures are 88 characters, matching TARGET_NAME_LENGTH in the
// experiment's scripts/gen_filterlist.py, because that is what the paired SMP
// cases send.
//
// # Cost of name normalization
//
// The experiment predates Test normalizing the name it is given (see
// matcher.go). Measured A/B on the same machine with these fixtures, at 100k
// entries and 88-character names:
//
//	                    before      after
//	Test (match)        ~105 ns     ~122 ns    (+15%, still 0 allocs)
//	NewMatcher          unchanged
//
// Lookup pays one extra pass over the name, bounded by its length. Construction
// is unaffected because entries are not normalized; an earlier revision did
// normalize them and cost ~4x here (100k: 1.45 ms -> 5.70 ms) while also
// widening prefix entries, which is why it was dropped.
//
// Note that Test returns before normalizing when no filter list is configured,
// so Agents without metric_filterlist pay none of this.
package metricname

import (
	"fmt"
	"math/rand"
	"runtime"
	"sort"
	"strings"
	"testing"
	"time"
)

// sizes matches the tiers generated by the experiment's
// scripts/generate_filterlist_cases.py: the 10k-60k sweep plus the 100k stress
// tier. Used by benchmarks only; the assertions below use testSizes so they
// stay cheap enough for every CI run.
var sizes = []int{10_000, 20_000, 30_000, 40_000, 50_000, 60_000, 100_000}

// testSizes is the smallest pair that still discriminates O(log n) from O(n):
// the smallest tier and the 10x stress tier.
var testSizes = []int{10_000, 100_000}

// Name construction mirrors the experiment's scripts/gen_filterlist.py exactly,
// so the inputs here (length, divergence position, sort behaviour) are those of
// the generated filter lists and the lading traffic that drives them. Letters,
// not digits, because lading's numeric `{{X-Y}}` ranges rewrite zero padding.
//
// Every name is targetNameLength characters. The two layouts differ only in
// where the constant padding sits, which is what separates "names are long"
// from "comparisons are deep":
//
//	tail: smp.filterlist.bench.metric.aaaaab<54 x's>   diverges at char 33
//	deep: smp.filterlist.bench.metric.<54 x's>aaaaab   diverges at char 87
const (
	alphabet         = "abcdefghijklmnopqrstuvwxyz"
	padChar          = 'x'
	indexWidth       = 6
	targetNameLength = 88
	matchPrefix      = "smp.filterlist.bench.metric"
	nomatchPrefix    = "smp.filterlist.bench.nomatch"
	// matchCorpusSize mirrors MATCH_CORPUS_SIZE (26**2) in gen_filterlist.py:
	// the shared head of every tier's list, which is what the traffic
	// generator draws guaranteed-match names from.
	matchCorpusSize = 676
)

// layouts are benchmarked separately, mirroring the paired SMP cases.
var layouts = []string{"tail", "deep"}

func indexChars(i int) string {
	buf := make([]byte, indexWidth)
	for p := indexWidth - 1; p >= 0; p-- {
		buf[p] = alphabet[i%len(alphabet)]
		i /= len(alphabet)
	}
	return string(buf)
}

func entryName(prefix string, i int, layout string) string {
	pad := targetNameLength - len(prefix) - 1 - indexWidth
	if pad < 0 {
		panic("targetNameLength too short for prefix plus index")
	}
	padding := strings.Repeat(string(padChar), pad)
	idx := indexChars(i)
	var suffix string
	if layout == "deep" {
		suffix = padding + idx
	} else {
		suffix = idx + padding
	}
	name := prefix + "." + suffix
	if len(name) != targetNameLength {
		panic(fmt.Sprintf("name %q is %d chars, want %d", name, len(name), targetNameLength))
	}
	return name
}

func metricName(i int, layout string) string {
	return entryName(matchPrefix, i, layout)
}

func nomatchName(i int, layout string) string {
	return entryName(nomatchPrefix, i, layout)
}

func buildNames(n int, layout string) []string {
	names := make([]string, n)
	for i := 0; i < n; i++ {
		names[i] = metricName(i, layout)
	}
	return names
}

// rawName returns a name that the intake would rewrite into entryName(i), so it
// exercises Test's normalization path and still matches the compiled list.
//
// The interior `%` becomes an underscore, which the following period then
// overwrites, so `smp%.filterlist...` normalizes back to `smp.filterlist...`.
func rawName(i int, layout string) string {
	return strings.Replace(metricName(i, layout), "smp.", "smp%.", 1)
}

// TestMatcherFixturesAreNormalized guards the validity of every measurement in
// this file. NewMatcher normalizes and drops entries, and Test normalizes its
// argument, so if the generated fixture names were not already normalized the
// benchmarks would silently measure the rewrite path instead of the lookup
// path, or measure a matcher with fewer entries than requested.
func TestMatcherFixturesAreNormalized(t *testing.T) {
	for _, layout := range layouts {
		for _, name := range []string{metricName(0, layout), metricName(matchCorpusSize, layout), nomatchName(0, layout)} {
			if !IsNormalized(name) {
				t.Errorf("fixture %q is not a normalized metric name; benchmarks would measure the rewrite path", name)
			}
			if len(name) != targetNameLength {
				t.Errorf("fixture %q is %d chars, want %d", name, len(name), targetNameLength)
			}
		}
	}

	// The matcher must keep every entry, i.e. none is rejected as unstorable.
	const n = 1000
	m := NewMatcher(buildNames(n, "tail"), false)
	if m.Len() != n {
		t.Errorf("matcher compiled %d entries, want %d: fixtures are being dropped", m.Len(), n)
	}
}

// TestMatcherTestIsAllocationFree pins the experiment's headline invariant:
// Matcher.Test does not allocate.
//
// This is the guard for normalization being on the lookup path. Normalize has
// an allocation-free fast path for already-normalized names, which is what real
// metric names overwhelmingly are; if that fast path is ever lost, every
// DogStatsD sample starts allocating and this test fails.
func TestMatcherTestIsAllocationFree(t *testing.T) {
	for _, layout := range layouts {
		for _, n := range testSizes {
			names := buildNames(n, layout)
			exact := NewMatcher(names, false)
			prefix := NewMatcher([]string{matchPrefix}, true)

			hit := metricName(n/2, layout)
			miss := nomatchName(n/2, layout)

			cases := []struct {
				name string
				m    *Matcher
				arg  string
				want bool
			}{
				{"match", &exact, hit, true},
				{"nomatch", &exact, miss, false},
				{"prefix-match", &prefix, hit, true},
				{"prefix-nomatch", &prefix, miss, false},
			}

			for _, c := range cases {
				t.Run(fmt.Sprintf("layout=%s/n=%d/%s", layout, n, c.name), func(t *testing.T) {
					if got := c.m.Test(c.arg); got != c.want {
						t.Fatalf("Test(%q) = %v, want %v", c.arg, got, c.want)
					}
					if allocs := testing.AllocsPerRun(100, func() { c.m.Test(c.arg) }); allocs != 0 {
						t.Errorf("Test allocated %.1f times per call, want 0", allocs)
					}
				})
			}
		}
	}
}

// TestMatcherTestAllocationsForNonNormalizedName pins the cost of the one case
// that cannot be allocation-free: a submitted name that the intake would
// rewrite. Such names have to be normalized before they can be compared, so
// they allocate. The point of pinning it is to know the number, and to notice
// if it grows.
func TestMatcherTestAllocationsForNonNormalizedName(t *testing.T) {
	normalized := metricName(1, "tail")
	raw := rawName(1, "tail")

	// Self-check the fixture: it must not already be normalized, and it must
	// normalize onto the entry, otherwise this measures the wrong thing.
	if IsNormalized(raw) {
		t.Fatalf("test input %q is already normalized, it cannot exercise the rewrite path", raw)
	}
	if got, ok := Normalize(raw); !ok || got != normalized {
		t.Fatalf("Normalize(%q) = (%q, %v), want (%q, true)", raw, got, ok, normalized)
	}

	m := NewMatcher(buildNames(10_000, "tail"), false)
	if !m.Test(raw) {
		t.Fatalf("Test(%q) = false, want true: raw name should match via its normalized form", raw)
	}

	// One allocation for the rewrite buffer, one for the resulting string.
	const maxAllocs = 2
	allocs := testing.AllocsPerRun(100, func() { m.Test(raw) })
	if allocs > maxAllocs {
		t.Errorf("Test on a non-normalized name allocated %.1f times per call, want <= %d", allocs, maxAllocs)
	}
	t.Logf("non-normalized name: %.0f allocs/call", allocs)
}

// TestMatcherConstructionAllocationBudget pins the experiment's finding that
// construction copies only string headers: a small, constant number of
// allocations and ~16 bytes per entry, regardless of how long the names are.
//
// A regression here means construction started copying name bytes, which turns
// a ~1.6 MB compile at 100k entries into a ~10 MB one.
func TestMatcherConstructionAllocationBudget(t *testing.T) {
	// A string header is 16 bytes on 64-bit platforms. The budget allows
	// generous headroom for slice growth while still failing loudly if the
	// name bytes (88 per entry) start being copied.
	const maxBytesPerEntry = 40

	for _, n := range testSizes {
		names := buildNames(n, "tail")
		t.Run(fmt.Sprintf("n=%d", n), func(t *testing.T) {
			var m Matcher
			bytesPerCall, allocs := measureAlloc(func() { m = NewMatcher(names, false) })
			if m.Len() != n {
				t.Fatalf("compiled %d entries, want %d", m.Len(), n)
			}

			perEntry := bytesPerCall / float64(n)
			if perEntry > maxBytesPerEntry {
				t.Errorf("construction allocated %.1f B/entry, want <= %d: name bytes are being copied",
					perEntry, maxBytesPerEntry)
			}

			// Allocation *count* must not scale with the number of entries.
			const maxAllocs = 8
			if allocs > maxAllocs {
				t.Errorf("construction made %.0f allocations for %d entries, want <= %d",
					allocs, n, maxAllocs)
			}
			t.Logf("n=%d: %.1f B/entry, %.0f allocs", n, perEntry, allocs)
		})
	}
}

// TestMatcherMemoryIsIndependentOfNameLength pins the finding that the compiled
// matcher costs the same per entry at 34 and at 88 character names, because
// only headers are copied. The experiment relied on this to conclude that RSS
// growth from long names lives in the config layers, not in the matcher.
func TestMatcherMemoryIsIndependentOfNameLength(t *testing.T) {
	const n = 10_000

	short := make([]string, n)
	long := make([]string, n)
	for i := 0; i < n; i++ {
		idx := indexChars(i)
		short[i] = "smp.filterlist.short." + idx
		long[i] = metricName(i, "tail")
	}
	if len(short[0]) >= len(long[0]) {
		t.Fatalf("fixture setup: short name %d chars is not shorter than long name %d chars", len(short[0]), len(long[0]))
	}

	shortBytes, _ := measureAlloc(func() { _ = NewMatcher(short, false) })
	longBytes, _ := measureAlloc(func() { _ = NewMatcher(long, false) })

	t.Logf("%d-char names: %.0f B; %d-char names: %.0f B", len(short[0]), shortBytes, len(long[0]), longBytes)

	// Names are 2.6x longer; allow a wide tolerance for allocator size classes
	// while still catching a change that makes cost track name length.
	const tolerance = 1.5
	if longBytes > shortBytes*tolerance {
		t.Errorf("construction with %d-char names allocated %.0f B against %.0f B with %d-char names (>%.1fx): matcher memory now tracks name length",
			len(long[0]), longBytes, shortBytes, len(short[0]), tolerance)
	}
}

// measureAlloc reports the average bytes and allocation count per call of fn,
// using the same runtime.ReadMemStats approach as the original experiment's
// B/construct metric. Allocation volume here is deterministic, so a handful of
// iterations is enough and is much cheaper than letting testing.Benchmark ramp
// up at 100k entries.
func measureAlloc(fn func()) (bytes, allocs float64) {
	const iterations = 5

	// Warm up so first-call lazy initialization is not attributed to fn.
	fn()

	runtime.GC()
	var before, after runtime.MemStats
	runtime.ReadMemStats(&before)
	for i := 0; i < iterations; i++ {
		fn()
	}
	runtime.ReadMemStats(&after)

	return float64(after.TotalAlloc-before.TotalAlloc) / float64(iterations),
		float64(after.Mallocs-before.Mallocs) / float64(iterations)
}

// TestMatcherLookupCostIsFlat pins the experiment's central result: lookup is
// O(log n), so per-metric cost is effectively flat from 10k to 100k entries.
//
// It asserts on the median rather than a tail percentile, and against a bound
// two orders of magnitude above the measured value, so scheduling noise on a
// busy CI machine cannot trip it. What it does catch decisively is the matcher
// degrading to a linear scan: at 100k entries with 88-character names that is
// hundreds of microseconds per lookup, not hundreds of nanoseconds.
//
// The p50/p95/p99 table is logged for comparison against the numbers recorded
// in the experiment's README.
func TestMatcherLookupCostIsFlat(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping latency sweep in -short mode")
	}

	// Measured p50 is ~50-60 ns. A linear scan would be ~10^5 ns.
	const maxMedian = 10 * time.Microsecond

	const samplesPerSize = 200_000
	rng := rand.New(rand.NewSource(42))

	t.Logf("%-6s %-8s %-10s %-10s %-10s", "layout", "n", "p50(ns)", "p95(ns)", "p99(ns)")
	for _, layout := range layouts {
		for _, n := range testSizes {
			m := NewMatcher(buildNames(n, layout), false)

			// Representative mixed workload, matching the lading traffic mix
			// in the paired SMP cases: 90% random background names that miss,
			// 5% guaranteed match from the shared corpus, 5% guaranteed
			// non-match from the disjoint namespace.
			lookups := make([]string, samplesPerSize)
			for i := range lookups {
				switch roll := rng.Float64(); {
				case roll < 0.90:
					lookups[i] = fmt.Sprintf("bg.random.metric.%d.%d", rng.Int63(), i)
				case roll < 0.95:
					lookups[i] = metricName(rng.Intn(matchCorpusSize), layout)
				default:
					lookups[i] = nomatchName(rng.Intn(matchCorpusSize), layout)
				}
			}

			durations := make([]time.Duration, samplesPerSize)
			for i, name := range lookups {
				start := time.Now()
				m.Test(name)
				durations[i] = time.Since(start)
			}
			sort.Slice(durations, func(i, j int) bool { return durations[i] < durations[j] })

			pct := func(p float64) time.Duration {
				idx := int(p * float64(len(durations)))
				if idx >= len(durations) {
					idx = len(durations) - 1
				}
				return durations[idx]
			}

			median := pct(0.50)
			t.Logf("%-6s %-8d %-10d %-10d %-10d", layout, n,
				median.Nanoseconds(), pct(0.95).Nanoseconds(), pct(0.99).Nanoseconds())

			if median > maxMedian {
				t.Errorf("layout=%s n=%d: median lookup %v exceeds %v; matching may no longer be O(log n)",
					layout, n, median, maxMedian)
			}
		}
	}
}

// BenchmarkMatcherConstruction measures NewMatcher, the one-time cost paid at
// startup and on every remote-config filter list update.
func BenchmarkMatcherConstruction(b *testing.B) {
	for _, layout := range layouts {
		for _, n := range sizes {
			names := buildNames(n, layout)
			b.Run(fmt.Sprintf("layout=%s/n=%d", layout, n), func(b *testing.B) {
				b.ReportAllocs()
				b.ResetTimer()
				for i := 0; i < b.N; i++ {
					_ = NewMatcher(names, false)
				}
			})
		}
	}
}

// BenchmarkMatcherTest measures Matcher.Test at each filter list size, for both
// a match and a non-match, mirroring the two traffic classes the paired SMP
// cases generate.
func BenchmarkMatcherTest(b *testing.B) {
	for _, layout := range layouts {
		for _, n := range sizes {
			m := NewMatcher(buildNames(n, layout), false)

			matchName := metricName(n/2, layout)
			missName := nomatchName(n/2, layout)

			b.Run(fmt.Sprintf("layout=%s/n=%d/match", layout, n), func(b *testing.B) {
				b.ReportAllocs()
				b.ResetTimer()
				for i := 0; i < b.N; i++ {
					if !m.Test(matchName) {
						b.Fatal("expected match")
					}
				}
			})

			b.Run(fmt.Sprintf("layout=%s/n=%d/nomatch", layout, n), func(b *testing.B) {
				b.ReportAllocs()
				b.ResetTimer()
				for i := 0; i < b.N; i++ {
					if m.Test(missName) {
						b.Fatal("expected no match")
					}
				}
			})
		}
	}
}

// BenchmarkMatcherTestNonNormalized measures the rewrite path: a submitted name
// that the intake would normalize before storing. Compare against
// BenchmarkMatcherTest to see what normalization costs when the fast path
// cannot be taken.
func BenchmarkMatcherTestNonNormalized(b *testing.B) {
	for _, n := range sizes {
		m := NewMatcher(buildNames(n, "tail"), false)
		raw := rawName(n/2, "tail")

		b.Run(fmt.Sprintf("n=%d", n), func(b *testing.B) {
			b.ReportAllocs()
			b.ResetTimer()
			for i := 0; i < b.N; i++ {
				m.Test(raw)
			}
		})
	}
}
