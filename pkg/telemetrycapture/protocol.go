// Package telemetrycapture provides bounded, command-armed observations of live
// delivery. It does not collect, serialize, sanitize, or deliver Agent telemetry.
package telemetrycapture

import "time"

const (
	// ProtocolVersion identifies the producer/coordinator IPC contract.
	ProtocolVersion = 1
	// MaxRecords includes unfinished observations and unacknowledged records.
	MaxRecords = 256
	// MaxBytes is the capture-owned memory budget in each producer.
	MaxBytes int64 = 128 << 20
	// MaxItemBytes bounds one complete logical observation, including its routes.
	MaxItemBytes int64 = 64 << 20
	// LeaseDuration disarms sessions whose coordinator has disappeared.
	LeaseDuration = 30 * time.Second
	// HeartbeatInterval is the coordinator's renewal interval.
	HeartbeatInterval = 5 * time.Second
	// MaxBatchRecords bounds one IPC read.
	MaxBatchRecords = 16
)

// Stream identifies an independently scheduled producer output.
type Stream string

const (
	Metrics        Stream = "metrics"
	Metadata       Stream = "metadata"
	Processes      Stream = "processes"
	Connections    Stream = "connections"
	Software       Stream = "software"
	AgentInventory Stream = "agent_inventory"
	HostInventory  Stream = "host_inventory"
	HostSystemInfo Stream = "host_system_info"
)

// State is a capture session's lifecycle state.
type State string

const (
	Prepared State = "prepared"
	Active   State = "active"
	Stopping State = "stopping"
	Stopped  State = "stopped"
	Failed   State = "failed"
)

// Identity identifies a running process, independently of its executable version.
type Identity struct {
	Role       string `json:"role"`
	InstanceID string `json:"instance_id"`
	Version    string `json:"version"`
	Commit     string `json:"commit"`
}

// Capability must be registered only after the corresponding producer starts.
type Capability struct {
	Stream          Stream           `json:"stream"`
	Cadence         time.Duration    `json:"cadence"`
	ConnectionOwner string           `json:"connection_owner,omitempty"`
	MetricSchedules []MetricSchedule `json:"metric_schedules,omitempty"`
}

// MetricSchedule describes a scheduled, supported check family. Its cadence is
// independent of the serializer flush cadence in the metrics capability.
type MetricSchedule struct {
	Family  string        `json:"family"`
	Cadence time.Duration `json:"cadence"`
}

// Control is used by all session control operations. IDs are opaque, bounded,
// URL-safe tokens generated by the coordinator, never telemetry-derived values.
type Control struct {
	ProtocolVersion int    `json:"protocol_version"`
	SessionID       string `json:"session_id"`
}

// PrepareRequest selects a subset of the producer's running capabilities.
type PrepareRequest struct {
	Control
	Streams []Stream `json:"streams"`
}

// ReadRequest acknowledges all records through Cursor before reading the next
// batch. Only previously returned sequences may be acknowledged.
type ReadRequest struct {
	Control
	Cursor uint64 `json:"cursor"`
}

// Status contains control-plane data only. It must never contain raw records.
type Status struct {
	ProtocolVersion int          `json:"protocol_version"`
	Producer        Identity     `json:"producer"`
	Capabilities    []Capability `json:"capabilities"`
	SessionID       string       `json:"session_id,omitempty"`
	State           State        `json:"state,omitempty"`
	ActivatedAt     time.Time    `json:"activated_at"`
	StoppedAt       time.Time    `json:"stopped_at"`
	FinalSequence   uint64       `json:"final_sequence"`
	Acknowledged    uint64       `json:"acknowledged"`
	Failures        uint64       `json:"failures"`
	Drops           uint64       `json:"drops"`
}

// Route describes an initial forwarding decision. No URL authority, query,
// credential, or transport retry data belongs in this structure.
type Route struct {
	PayloadID   uint64    `json:"payload_id"`
	Ordinals    []uint64  `json:"ordinals,omitempty"`
	Endpoint    string    `json:"endpoint"`
	Protocol    string    `json:"protocol"`
	Destination string    `json:"destination"`
	EnqueuedAt  time.Time `json:"enqueued_at"`
}

// Point preserves fractional timestamps independently of the wire protocol.
type Point struct {
	Timestamp float64 `json:"timestamp"`
	Value     float64 `json:"value"`
}

// Series is an owned semantic copy, made before serializer-side mutation.
type Series struct {
	Ordinal  uint64   `json:"ordinal"`
	Name     string   `json:"name"`
	Source   uint32   `json:"source"`
	Type     int32    `json:"type"`
	Interval int64    `json:"interval"`
	Host     string   `json:"host"`
	Device   string   `json:"device"`
	Tags     []string `json:"tags"`
	Points   []Point  `json:"points"`
}

// HostMetadata is a credential-free projection. It deliberately has no field
// for API keys, resources, configuration, or cloud/container metadata.
type HostMetadata struct {
	AgentVersion string                       `json:"agent_version"`
	UUID         string                       `json:"uuid"`
	Hostname     string                       `json:"hostname"`
	OS           string                       `json:"os"`
	AgentFlavor  string                       `json:"agent_flavor"`
	CPUCores     int                          `json:"cpu_cores"`
	Machine      string                       `json:"machine"`
	Platform     string                       `json:"platform"`
	MacVersion   string                       `json:"mac_version"`
	MacMachine   string                       `json:"mac_machine"`
	Windows      []string                     `json:"windows"`
	NetworkID    string                       `json:"network_id"`
	HostTags     map[string][]string          `json:"host_tags"`
	Gohai        map[string]map[string]string `json:"gohai"`
}

// Message holds an owned, complete software event before batch aggregation.
type Message struct {
	Body      []byte `json:"body"`
	Timestamp int64  `json:"timestamp"`
}

// Chunk holds an already encoded production body and only the headers needed
// to decode it. Adapters copy complete ordered groups; workers validate them.
type Chunk struct {
	Body    []byte            `json:"body"`
	Headers map[string]string `json:"headers"`
}

// Payload contains exactly one semantic observation or complete encoded group.
// Adapters must reserve capacity before allocating any of its owned data.
type Payload struct {
	Inventory *Inventory    `json:"inventory,omitempty"`
	Series    []Series      `json:"series,omitempty"`
	Metadata  *HostMetadata `json:"metadata,omitempty"`
	Software  *Message      `json:"software,omitempty"`
	Chunks    []Chunk       `json:"chunks,omitempty"`
	Routes    []Route       `json:"routes,omitempty"`
}

// Record is immutable after admission. A cycle can contain multiple chunks,
// but it has a single sequence, observation time, and collection boundary.
type Record struct {
	ProtocolVersion int           `json:"protocol_version"`
	SessionID       string        `json:"session_id"`
	Producer        Identity      `json:"producer"`
	Sequence        uint64        `json:"sequence"`
	CycleID         uint64        `json:"cycle_id"`
	Stream          Stream        `json:"stream"`
	CollectedAt     time.Time     `json:"collected_at"`
	ObservedAt      time.Time     `json:"observed_at"`
	Cadence         time.Duration `json:"cadence"`
	Payload         Payload       `json:"payload"`
}
