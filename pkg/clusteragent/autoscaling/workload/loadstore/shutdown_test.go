package loadstore

import (
	"context"
	"testing"
	"testing/synctest"
)

func TestCleanupExitsOnCancellation(t *testing.T) {
	synctest.Test(t, func(t *testing.T) {
		ctx, cancel := context.WithCancel(t.Context())
		defer cancel()
		NewEntityStore(ctx)
		synctest.Wait()
		cancel()
		synctest.Wait()
	})
}
