//go:build linux && bpf

package oomkill

// oomStatsVXLayout freezes the layout of struct oom_stats at version oom_stats_vX, so that the
// layout cannot change without bumping the version marker. The marker tells a new system-probe
// whether it can decode the values of the map pinned by a previous one.
//
// Never edit this struct. When changing struct oom_stats:
//  1. bump the version marker in oom-kill-kern-user.h, e.g. oom_stats_vX -> oom_stats_vY
//  2. bump the marker type in c_types.go, e.g. type oomStatsVY C.oom_stats_vY
//  3. regenerate c_types_linux.go with bazel run :c_types_godefs
//  4. replace this struct with oomStatsVYLayout, a copy of the generated oomStats
//
// The field names must be the ones generated by cgo for the conversion below to compile.
//
//nolint:revive
type oomStatsV2Layout struct {
	Oom_stats_version oomStatsV2
	Mem               cgroupMemoryStats
	Victim_pid        uint32
	Trigger_pid       uint32
	Victim_comm       [16]byte
	Trigger_comm      [16]byte
	Score             int64
	Pages             uint64
	Memcg_oom         uint32
	Score_adj         int16
	Pad               int16
	Cgroup_name       [129]byte
	Pad_cgo_0         [7]byte
}

// Fails to compile if the generated oomStats differs from the frozen layout of its version
var _ = oomStatsV2Layout(oomStats{})
