package tagname

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

var updateTables = flag.Bool("update-unicode-tables", false, "rewrite testdata/unicode from the Go toolchain's unicode package")

// unicodeTables renders the character data of SPEC.md §3.2 and §3.3 from the
// Go toolchain this test is built with.
//
// The files are the language-neutral definition of Letter, Digit and
// Lowercase that other implementations generate their tables from. This test
// fails whenever the toolchain's data differs from them, which is the signal
// that a Go upgrade changed the Unicode version (see SPEC.md §11).
func unicodeTables() map[string]string {
	header := func(what string) string {
		return fmt.Sprintf("# %s\n#\n# Unicode %s, as exposed by Go's unicode package. Generated by\n# TestUnicodeTables in this package with -update-unicode-tables. Do not edit.\n#\n# unicode_version: %s\n",
			what, unicode.Version, unicode.Version)
	}

	ranges := func(is func(rune) bool) string {
		var b strings.Builder
		for r := rune(0); r <= unicode.MaxRune; r++ {
			if !is(r) {
				continue
			}
			start := r
			for r+1 <= unicode.MaxRune && is(r+1) {
				r++
			}
			fmt.Fprintf(&b, "%04X..%04X\n", start, r)
		}
		return b.String()
	}

	var lower strings.Builder
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if l := unicode.ToLower(r); l != r {
			fmt.Fprintf(&lower, "%04X %04X\n", r, l)
		}
	}

	return map[string]string{
		"letter.txt": header("Letter (SPEC.md §3.2): code points of general category L (Lu, Ll, Lt, Lm, Lo).\n# One inclusive range per line, hexadecimal.") +
			ranges(unicode.IsLetter),
		"digit.txt": header("Digit (SPEC.md §3.2): code points of general category Nd.\n# One inclusive range per line, hexadecimal.") +
			ranges(unicode.IsDigit),
		"lowercase.txt": header("Lowercase (SPEC.md §3.3): the simple lowercase mapping.\n# One mapping per line, hexadecimal: <code point> <lowercase>. Code points\n# not listed map to themselves.") +
			lower.String(),
	}
}

// TestUnicodeTables checks testdata/unicode against the toolchain. To rewrite
// the files, run the test under `bazel run`, which exposes the source tree:
//
//	bazel run //pkg/metrics/tagname:tagname_test -- -test.run TestUnicodeTables -update-unicode-tables
func TestUnicodeTables(t *testing.T) {
	dir := filepath.Join("testdata", "unicode")
	for name, want := range unicodeTables() {
		if *updateTables {
			ws := os.Getenv("BUILD_WORKSPACE_DIRECTORY")
			require.NotEmpty(t, ws, "-update-unicode-tables must be run with `bazel run`")
			out := filepath.Join(ws, "pkg", "metrics", "tagname", dir)
			require.NoError(t, os.MkdirAll(out, 0o755))
			require.NoError(t, os.WriteFile(filepath.Join(out, name), []byte(want), 0o644))
			continue
		}
		path := filepath.Join(dir, name)
		got, err := os.ReadFile(path)
		require.NoError(t, err)
		assert.Equal(t, want, string(got), "%s is out of date with this Go toolchain's Unicode data (%s); see SPEC.md §11", path, unicode.Version)
	}
}
