// TestNoAgentIntroducedDuplicates pushes a generated corpus of spans through
// the agent pipeline, with the real trace writers sending to a local intake,
// and prints the values the agent wrote to more than one location of the trace
// payloads it sends. It is report-only: it never fails on findings. Run it
// with -test.v (and --test_output=all under Bazel) to see the report, and add
// -dupcheck.verbose to list every occurrence group.
func TestNoAgentIntroducedDuplicates(t *testing.T) {
	inputs := newDupcheckInputs(t, dupcheck.NewCorpus(*dupcheckSeed))
	report := dupcheck.NewReport(*dupcheckSeed)
	for _, c := range dupcheckConfigs {
		t.Run(c.name, func(t *testing.T) {
			findings := newDupcheckPipeline(t, c).run(t, inputs, nil).findings()
			for _, stage := range dupcheckStages {
				fs := findings[stage]
				for i := range fs {
					fs[i].Context = "config=" + c.name + " " + fs[i].Context
				}
				report.Add(stage, fs...)
			}
		})
	}
	report.Print(t, *dupcheckVerbose)
	logSpanTypeCoverage(t)
}

// logSpanTypeCoverage prints the span types that pkg/trace switches on and
// that are missing from dupcheck.CorpusSpanTypes. It never fails. The
// pkg/trace sources are found from the working directory, so the check is
// skipped where they aren't available, as under Bazel.
func logSpanTypeCoverage(t *testing.T) {
	// The test runs in pkg/trace/testutil/dupcheck.
	dir, err := filepath.Abs(".")
	root := filepath.Dir(filepath.Dir(dir))
	if err == nil {
		_, err = os.Stat(filepath.Join(root, "agent", "obfuscate.go"))
	}
	if err != nil {
		t.Logf("dupcheck coverage: span type check skipped, pkg/trace sources not found: %v", err)
		return
	}
	labels, err := dupcheck.SpanTypeCaseLabels(root)
	if err != nil {
		t.Logf("dupcheck coverage: span type check skipped: %v", err)
		return
	}
	t.Logf("dupcheck coverage: %d string case labels in pkg/trace switches on a span type, missing from CorpusSpanTypes: %q", len(labels), dupcheck.MissingCorpusSpanTypes(labels))
}

// Processing stages and kinds of injected duplicates of the checker self-test.
var (
	dupcheckProcessingStages = []string{stageV04, stageV1, stageOTLPProcessing}
	dupcheckInjectionKinds   = []string{injectionFromTopLevel, injectionFromAttribute, injectionOverwritten}
)

// TestDupcheckDetectsInjectedDuplicates tests the checker, not the agent: for
// every configuration and injection kind, a span modifier injects a duplicate
// of that kind into every span of the corpus: a new attribute copying a
// top-level field, a new attribute copying another attribute, or an existing
// attribute overwritten with a copy of another field. Every injection whose
// equality survives processing, as seen in the payloads the agent sent, must
// be reported, every span type sent must have such an injection for each
// kind and processing stage, and nothing else new may be reported.
func TestDupcheckDetectsInjectedDuplicates(t *testing.T) {
	corpus := dupcheck.NewCorpus(*dupcheckSeed)
	addGeneratedTraces(corpus)
	addOverwriteTargets(corpus)
	inputs := newDupcheckInputs(t, corpus)

	for _, c := range dupcheckConfigs {
		t.Run(c.name, func(t *testing.T) {
			baseline := newDupcheckPipeline(t, c).run(t, inputs, nil).findings()
			for _, kind := range dupcheckInjectionKinds {
				t.Run(kind, func(t *testing.T) {
					injectors := make(map[string]*dupcheckInjector)
					injected := newDupcheckPipeline(t, c).run(t, inputs, func(stage string) agent.SpanModifierWithV1 {
						injectors[stage] = &dupcheckInjector{kind: kind, injections: make(map[uint64]dupcheckInjection)}
						return injectors[stage]
					})
					findings, views := injected.findings(), injected.spanViews()
					for _, stage := range dupcheckProcessingStages {
						t.Run(stage, func(t *testing.T) {
							require.NotNil(t, injectors[stage])
							checkInjectedDuplicates(t, injectors[stage], views[stage], baseline[stage], findings[stage])
						})
					}
				})
			}
		})
	}
}

// checkInjectedDuplicates checks the findings of a stage run with injector
// against the findings of the same stage run without it.
func checkInjectedDuplicates(t *testing.T, injector *dupcheckInjector, views map[uint64]dupcheckSpanView, baselineFindings, injectedFindings []dupcheck.Finding) {
	require.NotEmpty(t, views, "the pipeline sent no span")
	remaining := make(map[string]int)
	for _, f := range baselineFindings {
		remaining[findingKey(f)]++
	}
	// reported holds, for each new finding, its first location paired with
	// each of the other ones.
	reported := make(map[string]bool)
	for _, f := range injectedFindings {
		if k := findingKey(f); remaining[k] > 0 {
			remaining[k]--
			continue
		}
		inj, ok := injector.injections[f.SpanID]
		if !ok || !slices.Contains(f.Locations, inj.injected) {
			t.Errorf("new finding not involving an injected duplicate: %s (%s)", f.Fingerprint(), f.Context)
			continue
		}
		for _, partner := range f.Locations[1:] {
			reported[pairKey(f.SpanID, f.Locations[0], partner)] = true
		}
	}

	eligibleByType := make(map[string]int)
	for _, view := range views {
		eligibleByType[view.typ] = 0
	}
	eligible := 0
	for _, spanID := range slices.Sorted(maps.Keys(injector.injections)) {
		inj := injector.injections[spanID]
		view, ok := views[spanID]
		if !ok || !inj.eligible(view) {
			continue
		}
		eligible++
		eligibleByType[view.typ]++
		if !reported[pairKey(spanID, inj.injected, inj.source)] && !reported[pairKey(spanID, inj.source, inj.injected)] {
			t.Errorf("injected duplicate not reported: %s %s == %s (span %d, type %q)", inj.kind, inj.injected, inj.source, spanID, view.typ)
		}
	}
	for _, typ := range slices.Sorted(maps.Keys(eligibleByType)) {
		if eligibleByType[typ] == 0 {
			t.Errorf("no eligible %s injection for span type %q", injector.kind, typ)
		}
	}
	t.Logf("%d eligible %s injections over %d span types", eligible, injector.kind, len(eligibleByType))
}

func findingKey(f dupcheck.Finding) string {
	return fmt.Sprintf("%d %s %s %v %q", f.SpanID, f.Rule, f.Change, f.Locations, f.Value)
}

func pairKey(spanID uint64, a, b dupcheck.Location) string {
	return fmt.Sprintf("%d %s %s", spanID, a, b)
}

// addOverwriteTargets adds a random attribute to the spans that have none,
// such as the generated spans, so that every span can get an
// overwritten duplicate.
func addOverwriteTargets(corpus *dupcheck.Corpus) {
	for i := range corpus.Traces {
		for j := range corpus.Traces[i].Spans {
			s := &corpus.Traces[i].Spans[j]
			if slices.ContainsFunc(slices.Collect(maps.Keys(s.Attributes)), func(k string) bool { return strings.HasPrefix(k, dupcheck.RandomKeyPrefix) }) {
				continue
			}
			if s.Attributes == nil {
				s.Attributes = make(map[string]string)
			}
			s.Attributes[dupcheck.RandomKeyPrefix+"overwrite_target"] = fmt.Sprintf("dupcheck-overwrite-target-%d-%d", i, j)
		}
	}
}

// addGeneratedTraces adds traces generated by testutil, including span
// events. They come from the unseeded global math/rand, so they are only used
// by the checker self-test, which compares two runs of the same inputs, and
// not by the report, whose output must be reproducible from its seed.
func addGeneratedTraces(corpus *dupcheck.Corpus) {
	spanConfig := &testutil.SpanConfig{MinTags: 4, MaxTags: 12, NumSpanEvents: 1}
	for range 10 {
		var specs []dupcheck.SpanSpec
		for _, s := range testutil.GenerateTrace(&testutil.TraceConfig{MinSpans: 2, MaxSpans: 5}, spanConfig) {
			spec := dupcheck.SpanSpec{Service: s.Service, Name: s.Name, Resource: s.Resource, Type: s.Type, Attributes: s.Meta}
			for _, e := range s.SpanEvents {
				spec.Events = append(spec.Events, dupcheck.EventSpec{Name: e.Name})
			}
			specs = append(specs, spec)
		}
		corpus.AddTrace(specs...)

		strs := idx.NewStringTable()
		specs = nil
		for _, s := range testutil.GenerateTraceV1(strs, &testutil.TraceConfig{MinSpans: 2, MaxSpans: 5}, spanConfig).Spans {
			spec := dupcheck.SpanSpec{Service: s.Service(), Name: s.Name(), Resource: s.Resource(), Type: s.Type(), Attributes: make(map[string]string)}
			for keyRef, v := range s.Attributes() {
				if sv, ok := v.GetValue().(*idx.AnyValue_StringValueRef); ok {
					spec.Attributes[strs.Get(keyRef)] = strs.Get(sv.StringValueRef)
				}
			}
			specs = append(specs, spec)
		}
		corpus.AddTrace(specs...)
	}
}

// dupcheckInputs are the corpus rendered in every input format. They are
// never handed to the agent, which mutates its input: each run processes
// deep copies.
type dupcheckInputs struct {
	v04  []*pb.TracerPayload
	v1   []*idx.InternalTracerPayload
	otlp []ptrace.ResourceSpans
}

const dupcheckBatchSize = 8

func newDupcheckInputs(t *testing.T, corpus *dupcheck.Corpus) *dupcheckInputs {
	require.NotEmpty(t, corpus.Traces)
	in := &dupcheckInputs{}
	for _, batch := range corpus.Batches(dupcheckBatchSize) {
		in.v04 = append(in.v04, dupcheck.TracerPayload(batch))
		in.v1 = append(in.v1, dupcheck.TracerPayloadV1(batch))
		in.otlp = append(in.otlp, dupcheck.ResourceSpans(batch))
	}
	return in
}

func cloneTracerPayloadV1(tp *idx.InternalTracerPayload) *idx.InternalTracerPayload {
	return idx.FromProto(proto.Clone(tp.ToProto()).(*idx.TracerPayload))
}

// dupcheckIntake stands for the Datadog intake: it decodes the trace payloads
// sent by the real writers.
type dupcheckIntake struct {
	server *httptest.Server
	mu     sync.Mutex
	traces []*pb.AgentPayload
	errs   []error
}

func newDupcheckIntake(t *testing.T) *dupcheckIntake {
	intake := &dupcheckIntake{}
	intake.server = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		err := intake.decode(r)
		intake.mu.Lock()
		if err != nil {
			intake.errs = append(intake.errs, err)
		}
		intake.mu.Unlock()
		w.WriteHeader(http.StatusOK)
	}))
	t.Cleanup(intake.server.Close)
	return intake
}

func (in *dupcheckIntake) decode(r *http.Request) error {
	var body io.Reader = r.Body
	if r.Header.Get("Content-Encoding") == "gzip" {
		gz, err := gzip.NewReader(r.Body)
		if err != nil {
			return err
		}
		defer gz.Close()
		body = gz
	}
	raw, err := io.ReadAll(body)
	if err != nil {
		return err
	}
	if r.URL.Path != "/api/v0.2/traces" {
		return fmt.Errorf("unexpected intake path %q", r.URL.Path)
	}
	var p pb.AgentPayload
	if err := proto.Unmarshal(raw, &p); err != nil {
		return err
	}
	in.mu.Lock()
	in.traces = append(in.traces, &p)
	in.mu.Unlock()
	return nil
}

func (in *dupcheckIntake) takeTraces(t *testing.T) []*pb.AgentPayload {
	in.mu.Lock()
	defer in.mu.Unlock()
	require.Empty(t, in.errs)
	traces := in.traces
	in.traces = nil
	return traces
}

// dupcheckNoopConcentrator drops the stats inputs of the agent: dupcheck only
// checks trace payloads.
type dupcheckNoopConcentrator struct{}

func (dupcheckNoopConcentrator) Start()              {}
func (dupcheckNoopConcentrator) Stop()               {}
func (dupcheckNoopConcentrator) Add(stats.Input)     {}
func (dupcheckNoopConcentrator) AddV1(stats.InputV1) {}

// dupcheckPipeline is an agent built by NewAgent, with its real trace writers
// flushing synchronously to a dupcheckIntake and a no-op concentrator.
type dupcheckPipeline struct {
	agnt    *agent.Agent
	intake  *dupcheckIntake
	otlp    *api.OTLPReceiver
	otlpOut chan *api.Payload
}

func newDupcheckPipeline(t *testing.T, c dupcheckConfig) *dupcheckPipeline {
	intake := newDupcheckIntake(t)
	cfg := config.New()
	cfg.Endpoints[0].Host = intake.server.URL
	cfg.Endpoints[0].APIKey = "dupcheck-api-key"
	cfg.SynchronousFlushing = true
	cfg.Hostname = "dupcheck-agent-hostname"
	// Without the query cache, the obfuscator starts no goroutine and needs no
	// stop, which the agent only exposes through Run.
	cfg.Obfuscation.Cache.Enabled = false
	cfg.DefaultEnv = "dupcheck-agent-env"
	translator, err := attributes.NewTranslator(componenttest.NewNopTelemetrySettings())
	require.NoError(t, err)
	cfg.OTLPReceiver.AttributesTranslator = translator
	if c.configure != nil {
		c.configure(cfg)
	}
	a := agent.NewAgent(context.Background(), cfg, telemetry.NewNoopCollector(), &statsd.NoOpClient{}, gzipcomp.NewComponent())
	a.Concentrator = dupcheckNoopConcentrator{}
	// NewAgent starts the senders of the stats writer. Run its loop so that
	// Stop can shut them down.
	go a.StatsWriter.Run()
	if c.setup != nil {
		c.setup(a)
	}
	otlpOut := make(chan *api.Payload, 1)
	p := &dupcheckPipeline{
		agnt:    a,
		intake:  intake,
		otlp:    api.NewOTLPReceiver(otlpOut, cfg, &statsd.NoOpClient{}, &timing.NoopReporter{}),
		otlpOut: otlpOut,
	}
	t.Cleanup(func() {
		a.TraceWriter.Stop()
		a.TraceWriterV1.Stop()
		a.StatsWriter.Stop()
	})
	return p
}

// dupcheckTracePair is the input of a processing stage and the agent payloads
// sent for it.
type dupcheckTracePair struct {
	in  *pb.TracerPayload
	out []*pb.AgentPayload
}

type dupcheckTracePairV1 struct {
	in  *idx.InternalTracerPayload
	out []*pb.AgentPayload
}

type dupcheckOTLPPair struct {
	in  ptrace.ResourceSpans
	out *pb.TracerPayload
}

// dupcheckOutput holds the inputs and outputs of every stage of a run.
type dupcheckOutput struct {
	v04            []dupcheckTracePair
	v1             []dupcheckTracePairV1
	otlpConversion []dupcheckOTLPPair
	otlpProcessing []dupcheckTracePair
}

// run pushes the inputs through every stage of the pipeline. newModifier, if
// set, returns the span modifier used by the agent during a stage.
func (p *dupcheckPipeline) run(t *testing.T, in *dupcheckInputs, newModifier func(stage string) agent.SpanModifierWithV1) *dupcheckOutput {
	a := p.agnt
	setModifier := func(stage string) {
		if newModifier != nil {
			m := newModifier(stage)
			a.SpanModifier, a.SpanModifierV1 = m, m
		}
	}
	source := func() *info.TagStats {
		return info.NewReceiverStats(true).GetTagStats(info.Tags{Lang: "go"})
	}
	out := &dupcheckOutput{}

	setModifier(stageV04)
	for _, tp := range in.v04 {
		a.Process(&api.Payload{TracerPayload: proto.Clone(tp).(*pb.TracerPayload), Source: source()})
		require.NoError(t, a.TraceWriter.FlushSync())
		out.v04 = append(out.v04, dupcheckTracePair{in: tp, out: p.intake.takeTraces(t)})
	}

	setModifier(stageV1)
	for _, tp := range in.v1 {
		a.ProcessV1(&api.PayloadV1{TracerPayload: cloneTracerPayloadV1(tp), Source: source()})
		require.NoError(t, a.TraceWriterV1.FlushSync())
		out.v1 = append(out.v1, dupcheckTracePairV1{in: tp, out: p.intake.takeTraces(t)})
	}

	setModifier(stageOTLPProcessing)
	for _, rs := range in.otlp {
		received := ptrace.NewResourceSpans()
		rs.CopyTo(received)
		_, err := p.otlp.ReceiveResourceSpans(context.Background(), received, http.Header{}, nil)
		require.NoError(t, err)
		converted := <-p.otlpOut
		out.otlpConversion = append(out.otlpConversion, dupcheckOTLPPair{in: rs, out: proto.Clone(converted.TracerPayload).(*pb.TracerPayload)})
		stageIn := proto.Clone(converted.TracerPayload).(*pb.TracerPayload)
		a.Process(converted)
		require.NoError(t, a.TraceWriter.FlushSync())
		out.otlpProcessing = append(out.otlpProcessing, dupcheckTracePair{in: stageIn, out: p.intake.takeTraces(t)})
	}
	return out
}

// findings runs the dupcheck checks on every stage of the run.
func (o *dupcheckOutput) findings() map[string][]dupcheck.Finding {
	findings := make(map[string][]dupcheck.Finding)
	for _, pair := range o.v04 {
		for _, ap := range pair.out {
			findings[stageV04] = append(findings[stageV04], dupcheck.CheckTracerPayload(pair.in, ap)...)
		}
	}
	for _, pair := range o.v1 {
		for _, ap := range pair.out {
			findings[stageV1] = append(findings[stageV1], dupcheck.CheckTracerPayloadV1(pair.in, ap)...)
		}
	}
	for _, pair := range o.otlpConversion {
		findings[stageOTLPConversion] = append(findings[stageOTLPConversion], dupcheck.CheckOTLPConversion(pair.in, pair.out)...)
	}
	for _, pair := range o.otlpProcessing {
		for _, ap := range pair.out {
			findings[stageOTLPProcessing] = append(findings[stageOTLPProcessing], dupcheck.CheckTracerPayload(pair.in, ap)...)
		}
	}
	return findings
}

// dupcheckSpanView holds the string values of a span sent by the agent and of
// the same span in the stage input, by dupcheck location.
type dupcheckSpanView struct {
	typ string
	in  map[dupcheck.Location]string
	out map[dupcheck.Location]string
}

// spanViews returns the views of the spans sent in the processing stages, by stage and span ID.
func (o *dupcheckOutput) spanViews() map[string]map[uint64]dupcheckSpanView {
	viewsV04 := func(pairs []dupcheckTracePair) map[uint64]dupcheckSpanView {
		views := make(map[uint64]dupcheckSpanView)
		for _, pair := range pairs {
			inSpans := make(map[uint64]*pb.Span)
			for _, c := range pair.in.Chunks {
				for _, s := range c.Spans {
					inSpans[s.SpanID] = s
				}
			}
			for _, ap := range pair.out {
				for _, tp := range ap.TracerPayloads {
					for _, c := range tp.Chunks {
						for _, s := range c.Spans {
							views[s.SpanID] = dupcheckSpanView{typ: s.Type, in: spanValues(inSpans[s.SpanID]), out: spanValues(s)}
						}
					}
				}
			}
		}
		return views
	}
	viewsV1 := make(map[uint64]dupcheckSpanView)
	for _, pair := range o.v1 {
		inSpans := make(map[uint64]*idx.InternalSpan)
		for _, c := range pair.in.Chunks {
			for _, s := range c.Spans {
				inSpans[s.SpanID()] = s
			}
		}
		for _, ap := range pair.out {
			for _, ptp := range ap.IdxTracerPayloads {
				for _, c := range idx.FromProto(ptp).Chunks {
					for _, s := range c.Spans {
						viewsV1[s.SpanID()] = dupcheckSpanView{typ: s.Type(), in: spanValuesV1(inSpans[s.SpanID()]), out: spanValuesV1(s)}
					}
				}
			}
		}
	}
	return map[string]map[uint64]dupcheckSpanView{
		stageV04:            viewsV04(o.v04),
		stageV1:             viewsV1,
		stageOTLPProcessing: viewsV04(o.otlpProcessing),
	}
}

func spanValues(s *pb.Span) map[dupcheck.Location]string {
	values := make(map[dupcheck.Location]string)
	if s == nil {
		return values
	}
	values[dupcheck.LocationService] = s.Service
	values[dupcheck.LocationName] = s.Name
	for k, v := range s.Meta {
		values[dupcheck.MetaLocation(k)] = v
	}
	return values
}

func spanValuesV1(s *idx.InternalSpan) map[dupcheck.Location]string {
	values := make(map[dupcheck.Location]string)
	if s == nil {
		return values
	}
	values[dupcheck.LocationService] = s.Service()
	values[dupcheck.LocationName] = s.Name()
	for k, v := range stringAttributesV1(s) {
		values[dupcheck.AttributeLocation(k)] = v
	}
	return values
}

func stringAttributesV1(s *idx.InternalSpan) map[string]string {
	attrs := make(map[string]string)
	for keyRef, v := range s.Attributes() {
		if sv, ok := v.GetValue().(*idx.AnyValue_StringValueRef); ok {
			attrs[s.Strings.Get(keyRef)] = s.Strings.Get(sv.StringValueRef)
		}
	}
	return attrs
}

// Kinds of duplicates injected by dupcheckInjector.
const (
	injectionFromTopLevel  = "created-from-top-level"
	injectionFromAttribute = "created-from-attribute"
	injectionOverwritten   = "overwritten"
)

const (
	injectedFromTopLevelKey  = "dupcheck.injected.from_top_level"
	injectedFromAttributeKey = "dupcheck.injected.from_attribute"
)

// dupcheckInjection is a duplicate injected into a span: the value of source
// copied to injected.
type dupcheckInjection struct {
	kind     string
	injected dupcheck.Location
	source   dupcheck.Location
}

// eligible reports whether the checker must report the injection, given the
// span in the stage input and as the agent sent it: the two locations must
// still be equal, long enough for the dup rule, not already equal in the
// stage input, and an injected attribute copying a top-level field must
// differ from its input value.
func (inj dupcheckInjection) eligible(view dupcheckSpanView) bool {
	v, ok := view.out[inj.injected]
	src, srcOK := view.out[inj.source]
	if !ok || !srcOK || v != src || len(v) < dupcheck.MinLen {
		return false
	}
	inV, inOK := view.in[inj.injected]
	if inSrc, ok := view.in[inj.source]; inOK && ok && inV == inSrc {
		return false
	}
	topLevelSource := inj.source == dupcheck.LocationService || inj.source == dupcheck.LocationName
	return !(topLevelSource && inOK && inV == v)
}

// dupcheckCandidate is a span field a duplicate can be copied from or into.
type dupcheckCandidate struct {
	loc   dupcheck.Location
	key   string
	value string
}

// dupcheckInjector is a span modifier injecting a duplicate of one kind into
// every span where it can.
type dupcheckInjector struct {
	kind       string
	injections map[uint64]dupcheckInjection
}

func (d *dupcheckInjector) ModifySpan(_ *pb.TraceChunk, s *pb.Span) {
	top := []dupcheckCandidate{{dupcheck.LocationService, "", s.Service}, {dupcheck.LocationName, "", s.Name}}
	if key, value, ok := d.inject(s.SpanID, top, s.Meta, dupcheck.MetaLocation); ok {
		if s.Meta == nil {
			s.Meta = make(map[string]string)
		}
		s.Meta[key] = value
	}
}

func (d *dupcheckInjector) ModifySpanV1(_ *idx.InternalTraceChunk, s *idx.InternalSpan) {
	top := []dupcheckCandidate{{dupcheck.LocationService, "", s.Service()}, {dupcheck.LocationName, "", s.Name()}}
	if key, value, ok := d.inject(s.SpanID(), top, stringAttributesV1(s), dupcheck.AttributeLocation); ok {
		s.SetStringAttribute(key, value)
	}
}

// inject chooses the duplicate to inject into a span and records it. It
// returns the attribute key to set and its value.
func (d *dupcheckInjector) inject(spanID uint64, top []dupcheckCandidate, attrs map[string]string, attrLocation func(string) dupcheck.Location) (string, string, bool) {
	rng := rand.New(rand.NewSource(int64(spanID)))
	long := func(cs []dupcheckCandidate) []dupcheckCandidate {
		return slices.DeleteFunc(slices.Clone(cs), func(c dupcheckCandidate) bool { return len(c.value) < dupcheck.MinLen })
	}
	var attributes, randomKeys []dupcheckCandidate
	for _, k := range slices.Sorted(maps.Keys(attrs)) {
		c := dupcheckCandidate{attrLocation(k), k, attrs[k]}
		attributes = append(attributes, c)
		if strings.HasPrefix(k, dupcheck.RandomKeyPrefix) {
			randomKeys = append(randomKeys, c)
		}
	}
	var key string
	var source dupcheckCandidate
	switch d.kind {
	case injectionFromTopLevel:
		if sources := long(top); len(sources) > 0 {
			key, source = injectedFromTopLevelKey, sources[rng.Intn(len(sources))]
		}
	case injectionFromAttribute:
		if sources := long(attributes); len(sources) > 0 {
			key, source = injectedFromAttributeKey, sources[rng.Intn(len(sources))]
		}
	case injectionOverwritten:
		if len(randomKeys) > 0 {
			target := randomKeys[rng.Intn(len(randomKeys))]
			sources := slices.DeleteFunc(long(append(slices.Clone(top), attributes...)), func(c dupcheckCandidate) bool {
				return c.value == target.value
			})
			if len(sources) > 0 {
				key, source = target.key, sources[rng.Intn(len(sources))]
			}
		}
	}
	if key == "" {
		return "", "", false
	}
	d.injections[spanID] = dupcheckInjection{kind: d.kind, injected: attrLocation(key), source: source.loc}
	return key, source.value, true
}
