// Package main emits the bootstrap program that generates easyjson marshalers
// for one source file.
//
// The easyjson CLI does this itself: it parses the annotated file, writes an
// equivalent program into the target package, and `go run`s it. That needs a Go
// toolchain and a writable source tree, neither of which exist inside a Bazel
// action. Splitting the two halves lets Bazel compile the program instead, and
// keeps the `easyjson:json` comments as the only place types are declared.
//
// easyjson's own parser package is not reusable here: it resolves the import
// path by shelling out to `go env GOMOD`, and there is no Go toolchain in the
// sandbox. The annotation scanning below mirrors parser.needType and its AST
// visitor, minus the -all flag that no CWS call site uses.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
	"text/template"
)

const (
	structComment     = "easyjson:json"
	structSkipComment = "easyjson:skip"
)

// The generated program mirrors what easyjson's bootstrap package writes, minus
// the flags no CWS call site uses.
var bootstrapTemplate = template.Must(template.New("bootstrap").Parse(`// Unless explicitly stated otherwise all files in this repository are licensed
// under the Apache License Version 2.0.
// This product includes software developed at Datadog (https://www.datadoghq.com/).
// Copyright 2016-present Datadog, Inc.

// Code generated by //pkg/security/generators/easyjson_bootstrap. DO NOT EDIT.

// Package main generates easyjson marshalers for {{.PkgPath}}.
package main

import (
	"flag"
	"go/format"
	"os"

	"github.com/mailru/easyjson/gen"

	pkg "{{.PkgPath}}"
)

// run generates the marshalers into f.
//
// gen.Generator.Run writes the body to the io.Writer it is handed but emits the
// header with fmt.Println, straight to os.Stdout. The easyjson CLI hides that by
// passing os.Stdout as the writer; both have to point at the same file here or
// the header goes missing.
func run(g *gen.Generator, f *os.File) error {
	stdout := os.Stdout
	os.Stdout = f
	defer func() { os.Stdout = stdout }()

	return g.Run(f)
}

func main() {
	output := flag.String("output", "", "Path of the generated marshaler file")
	flag.Parse()

	g := gen.NewGenerator("{{.OutBasename}}")
	g.SetPkg("{{.PkgName}}", "{{.PkgPath}}")
	g.NoStdMarshalers()
{{- if .BuildTags}}
	g.SetBuildTags("{{.BuildTags}}")
{{- end}}

{{range .Types}}	g.Add((*pkg.{{.}})(nil))
{{end}}
	// os.Stdout has to be a real file, so the marshalers are written first and
	// gofmted in place afterwards. Buffering through an os.Pipe would deadlock
	// on the larger outputs.
	f, err := os.Create(*output)
	if err != nil {
		panic(err)
	}
	if err := run(g, f); err != nil {
		panic(err)
	}
	if err := f.Close(); err != nil {
		panic(err)
	}

	// easyjson gofmts the generator's raw output before writing it out. That is
	// also what turns the emitted "// +build" line into a //go:build pair.
	raw, err := os.ReadFile(*output)
	if err != nil {
		panic(err)
	}
	src, err := format.Source(raw)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, src, 0o644); err != nil {
		panic(err)
	}
}
`))

type bootstrap struct {
	PkgName     string
	PkgPath     string
	OutBasename string
	BuildTags   string
	Types       []string
}

// annotation reports the easyjson directives carried by a doc comment.
func annotation(doc *ast.CommentGroup) (skip, explicit bool) {
	if doc == nil {
		return
	}

	for _, c := range doc.List {
		text := c.Text
		if len(text) > 2 {
			switch text[1] {
			case '/':
				text = text[2:]
			case '*':
				text = text[2 : len(text)-2]
			}
		}

		for _, line := range strings.Split(text, "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, structSkipComment) {
				return true, false
			}
			if strings.HasPrefix(line, structComment) {
				return false, true
			}
		}
	}

	return
}

// annotatedTypes returns the package name and the names of every type marked
// with `easyjson:json` in the file.
func annotatedTypes(filename string) (string, []string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), filename, nil, parser.ParseComments)
	if err != nil {
		return "", nil, err
	}

	var types []string
	for _, decl := range f.Decls {
		decl, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}

		// A single-spec declaration carries its comment on the GenDecl, so the
		// annotation has to be considered for every spec it groups.
		groupSkip, groupExplicit := annotation(decl.Doc)

		for _, spec := range decl.Specs {
			spec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}

			skip, explicit := groupSkip, groupExplicit
			if !skip && !explicit {
				skip, explicit = annotation(spec.Doc)
			}
			if explicit && !skip {
				types = append(types, spec.Name.String())
			}
		}
	}

	// easyjson sorts the type list before emitting, and Generator.Run pops types
	// off a stack, so the order reaches the output. Sort to match the CLI.
	sort.Strings(types)

	return f.Name.String(), types, nil
}

func generate(input, output, packagePath, outBasename, buildTags string) error {
	pkgName, types, err := annotatedTypes(input)
	if err != nil {
		return err
	}
	if len(types) == 0 {
		return fmt.Errorf("no easyjson:json types found in %s", input)
	}

	// The easyjson CLI writes its bootstrap into the target package, so it can
	// reach unexported types; this one is a separate main package and cannot.
	// gen.Generator names types via reflection, so the way out is an exported
	// alias in the target package (`type Exported = unexported`), which reflects
	// back to the original name and leaves the output unchanged.
	for _, t := range types {
		if !ast.IsExported(t) {
			return fmt.Errorf(
				"%s: type %q is marked easyjson:json but is unexported; add an exported alias "+
					"(type %s = %s) in the package and mark that instead",
				input, t, strings.ToUpper(t[:1])+t[1:], t,
			)
		}
	}

	var buf bytes.Buffer
	if err := bootstrapTemplate.Execute(&buf, bootstrap{
		PkgName:     pkgName,
		PkgPath:     packagePath,
		OutBasename: outBasename,
		BuildTags:   buildTags,
		Types:       types,
	}); err != nil {
		return err
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}

	return os.WriteFile(output, src, 0o644)
}

func main() {
	var (
		input       string
		output      string
		packagePath string
		outBasename string
		buildTags   string
	)

	flag.StringVar(&input, "input", "", "Annotated .go file holding the easyjson:json comments")
	flag.StringVar(&output, "output", "", "Path of the generated bootstrap program")
	flag.StringVar(&packagePath, "package-path", "", "Go import path of the package being generated for")
	flag.StringVar(&outBasename, "out-basename", "", "Base name of the marshaler file the bootstrap will produce")
	flag.StringVar(&buildTags, "build-tags", "", "Build tags to stamp on the marshaler file")
	flag.Parse()

	if err := generate(input, output, packagePath, outBasename, buildTags); err != nil {
		panic(err)
	}
}
