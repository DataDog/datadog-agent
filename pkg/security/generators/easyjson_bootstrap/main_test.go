const source = `package fixture

// Marked is picked up.
// easyjson:json
type Marked struct{}

// Unmarked is ignored.
type Unmarked struct{}

// Skipped is excluded even though it looks eligible.
// easyjson:skip
type Skipped struct{}

// Aliased is a non-struct, which easyjson only accepts when marked explicitly.
// easyjson:json
type Aliased map[string]interface{}

// easyjson:json
type (
	GroupedA struct{}
	GroupedB struct{}
)

/*
easyjson:json
*/
type BlockCommented struct{}
`

func TestAnnotatedTypes(t *testing.T) {
	path := filepath.Join(t.TempDir(), "fixture.go")
	require.NoError(t, os.WriteFile(path, []byte(source), 0o600))

	pkgName, types, err := annotatedTypes(path)
	require.NoError(t, err)

	assert.Equal(t, "fixture", pkgName)
	// Sorted, because the order reaches the generated output.
	assert.Equal(t, []string{
		"Aliased",
		"BlockCommented",
		"GroupedA",
		"GroupedB",
		"Marked",
	}, types)
}

func TestGenerateRejectsUnexported(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "unexported.go")
	require.NoError(t, os.WriteFile(path, []byte("package fixture\n\n// easyjson:json\ntype hidden struct{}\n"), 0o600))

	err := generate(path, filepath.Join(dir, "bootstrap.go"), "", "example.com/fixture", "hidden_easyjson.go", "")
	require.Error(t, err)
	assert.Contains(t, err.Error(), "type Hidden = hidden")
}

const stubHeader = `// Unless explicitly stated otherwise all files in this repository are licensed
// under the Apache License Version 2.0.
// This product includes software developed at Datadog (https://www.datadoghq.com/).
// Copyright 2016-present Datadog, Inc.

// Code generated by //pkg/security/generators/easyjson_bootstrap. DO NOT EDIT.
`

const stubBody = `package fixture

import (
	jlexer "github.com/mailru/easyjson/jlexer"
	jwriter "github.com/mailru/easyjson/jwriter"
)

func (v First) MarshalEasyJSON(w *jwriter.Writer) {}

func (v *First) UnmarshalEasyJSON(l *jlexer.Lexer) {}

func (v Second) MarshalEasyJSON(w *jwriter.Writer) {}

func (v *Second) UnmarshalEasyJSON(l *jlexer.Lexer) {}
`

func TestGenerateStub(t *testing.T) {
	for _, tc := range []struct {
		name      string
		buildTags string
		want      string
	}{
		{name: "portable", want: stubHeader + "\n" + stubBody},
		{name: "platform-specific", buildTags: "linux", want: stubHeader + "\n//go:build linux\n\n" + stubBody},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "fixture.go")
			require.NoError(t, os.WriteFile(path, []byte("package fixture\n\n// easyjson:json\ntype Second struct{}\n\n// easyjson:json\ntype First struct{}\n"), 0o600))
			stub := filepath.Join(dir, "stub.go")

			require.NoError(t, generate(path, filepath.Join(dir, "bootstrap.go"), stub, "example.com/fixture", "fixture_easyjson.go", tc.buildTags))

			got, err := os.ReadFile(stub)
			require.NoError(t, err)
			assert.Equal(t, tc.want, string(got))
		})
	}
}

func TestGenerateWithoutStub(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "fixture.go")
	require.NoError(t, os.WriteFile(path, []byte("package fixture\n\n// easyjson:json\ntype First struct{}\n"), 0o600))

	require.NoError(t, generate(path, filepath.Join(dir, "bootstrap.go"), "", "example.com/fixture", "fixture_easyjson.go", ""))

	entries, err := os.ReadDir(dir)
	require.NoError(t, err)
	assert.Len(t, entries, 2, "only the input and the bootstrap are expected")
}

func TestAnnotatedTypesNoneFound(t *testing.T) {
	path := filepath.Join(t.TempDir(), "bare.go")
	require.NoError(t, os.WriteFile(path, []byte("package bare\n\ntype Plain struct{}\n"), 0o600))

	_, types, err := annotatedTypes(path)
	require.NoError(t, err)
	assert.Empty(t, types)
}
