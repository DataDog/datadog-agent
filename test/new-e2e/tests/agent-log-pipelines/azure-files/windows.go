// The smb-windows cell reads a share of a Windows Server VM instead of Azure
// Files. The VM is created in the same Azure environment as the AKS cluster,
// so it gets a private IP address on the subnet of the AKS nodes and the
// Fakeintake VM; the Agent connects to that address on port 445.
//
// The writer runs on the VM, against its own NTFS directory, which the share
// exports. A writer pod cannot write there: its CIFS volume comes from the
// Azure Files CSI driver. The VM runs the stock workload's logwriter.py on
// python.org's embeddable distribution, and sidecars.py in place of ledger.sh
// and appender.sh, which need a POSIX shell. Running the same writer keeps its
// records, rotation and journal identical to the other cells'; a PowerShell
// port would have to be kept in step with it and could not be tested here,
// where PowerShell is not installed.
//
// What the test does over SSH, with fileserver.ps1, is in windows_test.go: the
// storage pass creates the VM and the reader's password, the test prepares the
// share and the scheduled tasks before the Agent pass, and starts them once
// the Agent is ready.
const (
	windowsCellName = "smb-windows"
	// windowsServerName names the VM. Its computer name, az-<name>, must stay
	// within the 15 characters Windows allows.
	windowsServerName = "smbwin"
	// windowsReaderUser is the local user the Agent reads the share as. Its
	// password is generated by the storage pass and only ever written to the
	// cell's Secrets and, briefly, to a file on the VM.
	windowsReaderUser    = "ddlogreader"
	windowsPasswordBytes = 24
	windowsRoot          = `C:\azure-files-e2e`
	windowsTaskPrefix    = "azure-files-e2e"
	fileServerScript     = "fileserver.ps1"
	sidecarsScript       = "sidecars.py"
	// windowsPythonVersion is the last 3.12 release that python.org ships
	// Windows binaries for; the stock writer image runs 3.12 too. The script
	// only runs a python.exe that python.org signed.
	windowsPythonVersion = "3.12.10"
)

// windowsTasks are the scheduled tasks of the VM: the writer and its two
// sidecars, as in a writer pod.
var windowsTasks = []string{writerContainerName, ledgerContainerName, appenderContainerName}

var (
	//go:embed workload/sidecars.py
	sidecarsSource string
	//go:embed workload/fileserver.ps1
	fileServerSource string
)

// errWindowsWriterOptions explains why the smb-windows cell refuses options.
var errWindowsWriterOptions = errors.New("the Windows file server only runs the writer's default options, rename every minute at the root of the share; " +
	"unset the rotation mode, period, rate and streams")

// windowsPath joins the elements of a path on the VM.
func windowsPath(elements ...string) string {
	return strings.Join(elements, `\`)
}

func windowsPythonURL() string {
	return "https://www.python.org/ftp/python/" + windowsPythonVersion + "/python-" + windowsPythonVersion + "-embed-amd64.zip"
}

func windowsPythonDir() string {
	return windowsPath(windowsRoot, "python-"+windowsPythonVersion)
}

func windowsWorkloadDir() string { return windowsPath(windowsRoot, "workload") }
func windowsRunDir() string      { return windowsPath(windowsRoot, "run") }
func windowsLogsDir() string     { return windowsPath(windowsRoot, "logs") }
func windowsSecretsDir() string  { return windowsPath(windowsRoot, "secrets") }

// windowsPasswordFile is where the test puts the reader's password for
// fileserver.ps1, which deletes it once read.
func windowsPasswordFile() string { return windowsPath(windowsSecretsDir(), "reader-password") }

// windowsShareDir is the directory the cell's share exports.
func windowsShareDir(c cell) string {
	return windowsPath(windowsRoot, "shares", c.shareName)
}

// windowsLogPath is a task's console log for this run's share.
func windowsLogPath(c cell, task string) string {
	return windowsPath(windowsLogsDir(), c.shareName+"-"+task+".log")
}

// windowsTaskEnv is a task's environment: its writer pod container's, with the
// paths of the VM.
func (spec runSpec) windowsTaskEnv(c cell, task string) []envVar {
	var vars []envVar
	switch task {
	case writerContainerName:
		// The records name the writer like a pod's HOSTNAME does.
		vars = append(spec.writerEnv(c), envVar{"HOSTNAME", c.writerName})
	case ledgerContainerName:
		vars = append([]envVar{{"LOGWRITER_LOG_DIR", logMountPath}, {"LOGWRITER_LEDGER_SOURCE", "journal"}}, c.writer.streamEnv()...)
	case appenderContainerName:
		vars = spec.appenderEnv(c)
	}
	out := make([]envVar, 0, len(vars))
	for _, v := range vars {
		switch v.name {
		case "LOGWRITER_LOG_DIR":
			v.value = windowsShareDir(c)
		case "LOGWRITER_MARKER_JOURNAL_PATH":
			v.value = windowsPath(windowsShareDir(c), postRotationMarkerJournalName)
		}
		out = append(out, v)
	}
	return out
}

// windowsTaskScript is the cmd.exe wrapper a scheduled task runs: it sets the
// task's environment and runs its Python script with the console appended to
// the task's log. cmd.exe would expand or split a value with one of the
// characters refused here, and none of the values needs them.
func (spec runSpec) windowsTaskScript(c cell, task string) (string, error) {
	script, args := pythonWriterScript, ""
	if task != writerContainerName {
		script, args = sidecarsScript, " "+task
	}
	var b strings.Builder
	b.WriteString("@echo off\r\nrem The " + task + " of the Azure Files E2E's " + c.name + " cell, written by the test.\r\n")
	for _, v := range spec.windowsTaskEnv(c, task) {
		if strings.ContainsAny(v.name+v.value, "\"%^&|<>\r\n") {
			return "", fmt.Errorf("the %s task's %s cannot be set from cmd.exe: %q", task, v.name, v.value)
		}
		fmt.Fprintf(&b, "set \"%s=%s\"\r\n", v.name, v.value)
	}
	fmt.Fprintf(&b, "\"%s\" -u \"%s\"%s >> \"%s\" 2>&1\r\n",
		windowsPath(windowsPythonDir(), "python.exe"), windowsPath(windowsWorkloadDir(), script), args, windowsLogPath(c, task))
	return b.String(), nil
}

// windowsFiles are the files the test copies to the VM before it prepares the
// share, by path on the VM.
func (spec runSpec) windowsFiles(c cell) (map[string]string, error) {
	files := map[string]string{
		windowsPath(windowsWorkloadDir(), pythonWriterScript): pythonWriterSource,
		windowsPath(windowsWorkloadDir(), sidecarsScript):     sidecarsSource,
		windowsPath(windowsWorkloadDir(), fileServerScript):   fileServerSource,
	}
	for _, task := range windowsTasks {
		script, err := spec.windowsTaskScript(c, task)
		if err != nil {
			return nil, err
		}
		files[windowsPath(windowsRunDir(), task+".cmd")] = script
	}
	return files, nil
}

// fileServerCommand runs an action of fileserver.ps1 with its arguments, which
// never include a secret: the command is logged.
func fileServerCommand(action string, args ...string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "& '%s' %s", windowsPath(windowsWorkloadDir(), fileServerScript), action)
	for i := 0; i+1 < len(args); i += 2 {
		fmt.Fprintf(&b, " -%s '%s'", args[i], args[i+1])
	}
	return b.String()
}

// windowsPrepareCommand prepares the share of the cell for this run.
func windowsPrepareCommand(c cell) string {
	return fileServerCommand("prepare",
		"Root", windowsRoot,
		"ShareName", c.shareName,
		"UserName", windowsReaderUser,
		"PasswordFile", windowsPasswordFile(),
		"PythonUrl", windowsPythonURL(),
		"PythonDir", windowsPythonDir(),
		"TaskPrefix", windowsTaskPrefix,
	)
}

// windowsReadCommand prints the files of the cell's share that exist.
func windowsReadCommand(c cell, names ...string) string {
	quoted := make([]string, 0, len(names))
	for _, name := range names {
		quoted = append(quoted, "'"+windowsPath(windowsShareDir(c), name)+"'")
	}
	return fileServerCommand("read", "Root", windowsRoot) + " -Paths " + strings.Join(quoted, ",")
}

// windowsLogsCommand prints the console logs of the cell's tasks.
func windowsLogsCommand(c cell, task string) string {
	return fileServerCommand("read", "Root", windowsRoot) + " -Paths '" + windowsLogPath(c, task) + "'"
}

type randomPassword struct {
	pulumi.CustomResourceState
	Result pulumi.StringOutput `pulumi:"result"`
}

// newWindowsServer creates the Windows Server VM and exports it to the
// environment, with Windows Defender disabled as the framework's Windows
// provisioners do by default.
func newWindowsServer(azureEnv azureresources.Environment, env *azureFilesEnv) error {
	vm, err := compute.NewVM(azureEnv, windowsServerName, compute.WithOS(componentsos.WindowsServerDefault))
	if err != nil {
		return err
	}
	if err := vm.Export(azureEnv.Ctx(), &env.WindowsServer.HostOutput); err != nil {
		return err
	}
	_, err = defender.NewDefender(azureEnv.CommonEnvironment, vm, defender.WithDefenderDisabled())
	return err
}

// newWindowsReaderSecrets generates the password of the Windows reader
// account and stores it, with the account name, in the cell's Secrets: the
// Agent namespace's, which the Agent pod mounts, and the e2e namespace's,
// which the test reads to set the password on the VM. The password is a
// Pulumi secret, through the generic random provider token, so the suite
// needs no random SDK module.
func newWindowsReaderSecrets(azureEnv *azureresources.Environment, workload *kubecomp.Workload, c cell, kubeOpts, agentSecretOpts []pulumi.ResourceOption) error {
	ctx := azureEnv.Ctx()
	password := &randomPassword{}
	err := ctx.RegisterResource("random:index/randomPassword:RandomPassword", c.secretName()+"-password", pulumi.Map{
		"length": pulumi.Int(windowsPasswordBytes),
		// Windows requires three of the four character classes; these
		// specials need no quoting anywhere the password goes.
		"special":         pulumi.Bool(true),
		"overrideSpecial": pulumi.String("-_.!"),
		"minUpper":        pulumi.Int(2),
		"minLower":        pulumi.Int(2),
		"minNumeric":      pulumi.Int(2),
		"minSpecial":      pulumi.Int(2),
	}, password, pulumi.Parent(workload), azureEnv.WithProviders(config.ProviderRandom),
		// The generated SDK marks these outputs secret; a generic
		// registration has to ask for it, or the state would keep the
		// password in plain text.
		pulumi.AdditionalSecretOutputs([]string{"result", "bcryptHash"}))
	if err != nil {
		return err
	}
	secret := pulumi.ToSecret(password.Result).(pulumi.StringOutput)
	for _, target := range []struct {
		name, namespace string
		opts            []pulumi.ResourceOption
	}{
		{c.secretName(), e2eNamespace, kubeOpts},
		{c.secretName() + "-agent", agentNamespace, agentSecretOpts},
	} {
		if _, err := corev1.NewSecret(ctx, target.name, &corev1.SecretArgs{
			Metadata: metav1.ObjectMetaArgs{
				Name:      pulumi.String(c.secretName()),
				Namespace: pulumi.String(target.namespace),
				Labels: pulumi.StringMap{
					partOfLabel: pulumi.String(partOfLabelValue),
					cellLabel:   pulumi.String(c.name),
				},
			},
			StringData: pulumi.StringMap{
				accountNameSecretKey: pulumi.String(windowsReaderUser),
				accountKeySecretKey:  secret,
			},
		}, target.opts...); err != nil {
			return err
		}
	}
	return nil
}
