#!/usr/bin/env python3
"""Generate/check memory diagnostics for endpoint routing and the existing MRF allowlist."""

import copy
import sys
from pathlib import Path

import yaml


def yaml_load(value):
    return yaml.load(value, Loader=yaml.CSafeLoader)


def yaml_dump(value, **kwargs):
    return yaml.dump(value, Dumper=yaml.CSafeDumper, **kwargs)


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent.parent
DEST = SOURCE
CHECK = "--check" in sys.argv
P = "http://127.0.0.1:9091"
S = "http://127.0.0.1:9092"


def read(path):
    return yaml_load(path.read_text())


def store_file(path, content):
    if CHECK:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Generated file differs: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def write(path, data):
    store_file(
        path,
        "# Generated by metrics-endpoint-routing/memory-diagnostics/generate.py.\n" + yaml_dump(data, sort_keys=False),
    )


def main():
    template = SOURCE / "metrics-endpoint-routing/templates"
    base = read(template / "datadog.yaml")
    lading = read(template / "lading.yaml")
    definitions = [("control", 0), ("mrf_unfiltered", 0)]
    definitions += [(kind, size) for kind in ("endpoint", "mrf") for size in (1000, 100000)]
    definitions += [("shared", 100000)]
    for kind, size in definitions:
        name = f"heap_{kind}" + (f"_{size}" if size else "")
        cfg = copy.deepcopy(base)
        cfg["expvar_port"] = 5000
        entries = []
        if size:
            source_case = SOURCE / f"cases/matched_exact_{size}_memory/datadog-agent/datadog.yaml"
            entries = read(source_case)["experimental"]["metrics_endpoint_routing"]["metric_allowlist"][P]
            assert len(entries) == len(set(entries)) == size
        if kind in ("endpoint", "shared"):
            targets = [P, S] if kind == "shared" else [P]
            cfg["experimental"] = {
                "metrics_endpoint_routing": {"metric_allowlist": {url: list(entries) for url in targets}}
            }
        if kind.startswith("mrf"):
            # Preserve filtered destination 9091 and unfiltered destination 9092.
            cfg["dd_url"] = S
            del cfg["additional_endpoints"]
            cfg["multi_region_failover"] = {
                "enabled": True,
                "failover_metrics": True,
                "dd_url": P,
                "api_key": "foo00000001",
            }
            if size:
                cfg["multi_region_failover"]["metric_allowlist"] = entries
        exp = read(template / "experiment.yaml")
        exp["optimization_goal"] = "memory"
        exp["target"]["environment"].update(
            HEAP_CASE=name,
            HEAP_VARIANT="{{ variant }}",
            HEAP_REPLICATE="{{ replicate_index }}",
            HEAP_JOB="{{ job_id }}",
        )
        exp["target"]["environment"]["DD_API_KEY"] = "foo00000002" if kind.startswith("mrf") else "foo00000001"
        exp["target"]["command"] = "/bin/sh /etc/datadog-agent/run_with_heap.sh"
        case = DEST / "cases" / name
        write(case / "experiment.yaml", exp)
        write(case / "datadog-agent/datadog.yaml", cfg)
        write(case / "lading/lading.yaml", lading)
        store_file(case / "datadog-agent/capture_heap.py", (ROOT / "capture_heap.py").read_text())
        store_file(
            case / "datadog-agent/run_with_heap.sh",
            "#!/bin/sh\nexport HEAP_AGENT_PID=$$\n/opt/datadog-agent/embedded/bin/python3 /etc/datadog-agent/capture_heap.py &\nexec /opt/datadog-agent/bin/agent/agent run -c /etc/datadog-agent/datadog.yaml\n",
        )
        store_file(case / "datadog-agent/conf.d/.keep", "")
    print(f"{'Checked' if CHECK else 'Generated'} {len(definitions)} memory diagnostic cases")


if __name__ == "__main__":
    main()
