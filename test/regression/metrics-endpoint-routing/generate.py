#!/usr/bin/env python3
"""Render/check the Agent port of Saluki PR #2653's matched SMP cases."""

import argparse
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
CASES_ROOT = ROOT.parent / "cases"
LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
DUMPER = yaml.SafeDumper
PRIMARY = "http://127.0.0.1:9091"
SECONDARY = "http://127.0.0.1:9092"
SIZES = (1000, 10000, 100000)
SUFFIXES = ("", ".max", ".median", ".avg", ".count", ".95percentile")
NAMES = [f"routing.metric.{i}" for i in range(10000, 10100)]
# Agent-only background series; reserve entries without changing total list size.
# No integrations are configured. Revisit this set if more background series appear.
AGENT_NAMES = (
    "datadog.agent.started",
    "datadog.agent.running",
    "datadog.agent.python.version",
    "datadog.agent.check_ready",
)
HEADER = "# Generated by test/regression/metrics-endpoint-routing/generate.py; do not edit.\n"


def read_template(name):
    return yaml.load((ROOT / "templates" / name).read_text(), Loader=LOADER)


def render():
    files = {}
    base_agent = read_template("datadog.yaml")
    experiment = read_template("experiment.yaml")
    lading = read_template("lading.yaml")
    generator = lading["generator"][0]["unix_datagram"]
    assert generator["path"] == base_agent["dogstatsd_socket"]
    assert generator["variant"]["dogstatsd"]["metric_names"] == ["routing.metric.{{10000-10099}}"]
    assert generator["variant"]["dogstatsd"]["timestamp"]["probability"] == 0
    assert {b["http"]["binding_addr"] for b in lading["blackhole"]} == {"127.0.0.1:9091", "127.0.0.1:9092"}
    assert base_agent["data_plane"]["enabled"] is False
    assert base_agent["dd_url"] == PRIMARY and set(base_agent["additional_endpoints"]) == {SECONDARY}
    assert base_agent["histogram_aggregates"] == ["max", "median", "avg", "count"]
    assert base_agent["histogram_percentiles"] == ["0.95"]
    assert base_agent["histogram_copy_to_distribution"] is False
    assert base_agent["serializer_compressor_kind"] == "zstd"
    assert all(base_agent["use_v3_api"]["series"]["endpoints"][url] == "true" for url in (PRIMARY, SECONDARY))
    scenarios = [("matched_control", None, 0)]
    scenarios += [(f"matched_{kind}_{size}", kind, size) for kind in ("exact", "prefix") for size in SIZES]
    for scenario, kind, size in scenarios:
        agent = copy.deepcopy(base_agent)
        if kind:
            if kind == "exact":
                entries = [name + suffix for name in NAMES for suffix in SUFFIXES] + list(AGENT_NAMES)
                key = "metric_allowlist"
            else:
                entries = NAMES + ["datadog."]
                key = "metric_prefix_allowlist"
            entries += [f"routing.absent.{i}" for i in range(100000, 100000 + size - len(entries))]
            assert len(entries) == size and len(set(entries)) == size
            if kind == "prefix":
                ordered = sorted(entries)
                assert all(not right.startswith(left) for left, right in zip(ordered, ordered[1:], strict=False))
                assert all(any(name.startswith(prefix) for prefix in entries[:101]) for name in AGENT_NAMES)
            else:
                assert set(AGENT_NAMES).issubset(entries)
            agent["experimental"] = {"metrics_endpoint_routing": {key: {PRIMARY: entries}}}
        for goal in ("cpu", "memory"):
            case = f"{scenario}_{goal}"
            exp = copy.deepcopy(experiment)
            exp["optimization_goal"] = goal
            exp["target"]["profiling_environment"]["DD_INTERNAL_PROFILING_EXTRA_TAGS"] = f"experiment:{case}"
            for name, obj in (
                ("experiment.yaml", exp),
                ("datadog-agent/datadog.yaml", agent),
                ("lading/lading.yaml", lading),
            ):
                files[Path(case) / name] = HEADER + yaml.dump(obj, Dumper=DUMPER, sort_keys=False)
            files[Path(case) / "datadog-agent/conf.d/.keep"] = ""
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in cases differ from their templates")
    args = parser.parse_args()
    expected = render()
    case_names = {path.parts[0] for path in expected}
    actual = {p.relative_to(CASES_ROOT) for case in case_names for p in (CASES_ROOT / case).rglob("*") if p.is_file()}
    unexpected = actual - expected.keys()
    if unexpected:
        raise SystemExit(f"Unexpected generated files (remove explicitly if obsolete): {sorted(map(str, unexpected))}")
    mismatches = []
    for rel, content in expected.items():
        path = CASES_ROOT / rel
        if args.check:
            if not path.exists() or path.read_text() != content:
                mismatches.append(str(rel))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if mismatches:
        raise SystemExit("Regenerate stale/missing files:\n" + "\n".join(mismatches))
    action = "Checked" if args.check else "Generated"
    print(f"{action} 14 SMP cases (control + exact/prefix 1K/10K/100K, CPU and memory).")


if __name__ == "__main__":
    main()
